import { expect, it } from "vitest";
import { api, internal } from "../../convex/_generated/api";
import { asNewUser } from "./helpers";
import { stepWorkFixture, usefulStepResult } from "../fixtures/stepWork";
it("carries the exact saved plan's research into preparation without treating summaries as quoted page evidence", async () => {
  const { t, owner, slug, strategyId, stepKey, orgId } = await stepWorkFixture();
  const first = await owner.client.mutation(api.stepWork.start, { slug, strategyId, stepKey, requestKey: "source-context-initial" });
  const row = (await t.run(ctx => ctx.db.get(first.workId)))!;
  await t.mutation(internal.stepWork.finish, { workId: first.workId, error: "Isolated test checkpoint, not a provider failure." });
  await t.mutation(internal.engine.finishRun, { runId: row.runId, status: "failed" });
  await t.run(ctx => ctx.db.insert("planEvidence", { orgId, strategyId, runId: row.runId, hash: "isolated-test", createdAt: Date.now(), data: JSON.stringify({ research: [{ notes: "A current primary correction supersedes an old tutorial.", sources: [{ url: "https://vendor.example/manual" }], retrievedAt: Date.now() }] }) }));
  const next = await owner.client.mutation(api.stepWork.start, { slug, strategyId, stepKey, requestKey: "source-context-refreshed", refresh: true });
  const saved = (await t.run(ctx => ctx.db.get(next.workId)))!;
  const context = JSON.parse(saved.context);
  expect(context.step.key).toBe(stepKey);
  expect(context.planResearch[0].notes).toContain("primary correction");
  expect(context.planResearch[0].basis).toContain("not tested behavior");
  expect(JSON.parse(saved.cachedSources)).toEqual([]);
});
it("starts one quoted job for the exact step, reuses work and keeps completion/approval unchanged", async () => {
  const { t, owner, slug, strategyId, stepKey, orgId } = await stepWorkFixture();
  const quote = await owner.client.query(api.stepWork.quote, { slug });
  expect(quote.maxCostMicros).toBeGreaterThan(0);
  const args = { slug, strategyId, stepKey, requestKey: "one-preparation-request" };
  const first = await owner.client.mutation(api.stepWork.start, args);
  const initial = (await t.run(ctx => ctx.db.get(first.workId)))!;
  expect((await t.run(ctx => ctx.db.get(initial.runId)))?.estimateMicros).toBe(quote.maxCostMicros);
  expect((await owner.client.mutation(api.stepWork.start, args)).workId).toBe(first.workId);
  expect((await owner.client.mutation(api.stepWork.start, { ...args, requestKey: "second-tab-request" })).workId).toBe(first.workId);
  expect(await t.mutation(internal.stepWork.claim, { workId: first.workId })).toBe(true);
  expect(await t.mutation(internal.stepWork.claim, { workId: first.workId })).toBe(false);
  await t.mutation(internal.stepWork.finish, { workId: first.workId, result: JSON.stringify(usefulStepResult), sources: "[]" });
  const ref = await t.query(internal.stepWork.ref, { workId: first.workId });
  await t.mutation(internal.engine.finishRun, { runId: ref!.runId, status: "verified" });
  expect((await owner.client.mutation(api.stepWork.start, { ...args, requestKey: "open-already-prepared" })).workId).toBe(first.workId);
  expect((await owner.client.query(api.stepWork.view, { slug, strategyId, stepKey }))?.result?.drafts[0].body).toBe(usefulStepResult.drafts[0].body);
  await owner.client.mutation(api.stepWork.saveDraft, { slug, workId: first.workId, index: 0, expectedRevision: 0, body: "An owner-edited private draft." });
  await expect(owner.client.mutation(api.stepWork.saveDraft, { slug, workId: first.workId, index: 0, expectedRevision: 0, body: "A stale edit" })).rejects.toThrow(/newer edit/);
  expect((await t.run(ctx => ctx.db.get(strategyId)))?.status).toBe("needs_approval");
  expect(await t.run(ctx => ctx.db.query("planTaskProgress").collect())).toEqual([]);
  expect(await t.run(ctx => ctx.db.query("artifacts").collect())).toEqual([]);
  expect(await t.run(ctx => ctx.db.query("workflowRuns").collect())).toHaveLength(1);
  expect(JSON.parse(await t.query(internal.settings.exportData, { orgId })).preparedStepWork).toHaveLength(1);
  const update = await owner.client.mutation(api.stepWork.start, { ...args, requestKey: "explicit-improvement-request", refresh: true });
  expect(update.workId).not.toBe(first.workId);
  expect((await t.run(ctx => ctx.db.get(update.workId)))?.previousWork).toContain("An owner-edited private draft.");
  await t.mutation(internal.stepWork.finish, { workId: update.workId, error: "A later source check failed." });
  const latest = await owner.client.query(api.stepWork.view, { slug, strategyId, stepKey });
  expect(latest?.status).toBe("failed");
  expect(latest?.previousId).toBe(first.workId);
  const earlier = await owner.client.query(api.stepWork.view, { slug, strategyId, stepKey, workId: first.workId });
  expect(earlier?.historical).toBe(true);
  expect(earlier?.edits[0].body).toBe("An owner-edited private draft.");
  const failedRef = await t.query(internal.stepWork.ref, { workId: update.workId });
  await t.mutation(internal.engine.finishRun, { runId: failedRef!.runId, status: "failed" });
  const retry = await owner.client.mutation(api.stepWork.start, { ...args, requestKey: "retry-after-source-failure" });
  expect((await t.run(ctx => ctx.db.get(retry.workId)))?.previousWork).toContain("An owner-edited private draft.");
  await expect(owner.client.query(api.stepWork.view, { slug, strategyId, stepKey: "another-step", workId: first.workId })).rejects.toThrow(/another plan step/);
});
it("resumes one private question and preserves useful drafts and owner edits", async () => {
  const { t, owner, slug, strategyId, stepKey } = await stepWorkFixture();
  const first = await owner.client.mutation(api.stepWork.start, { slug, strategyId, stepKey, requestKey: "missing-detail-work" });
  const result = { ...usefulStepResult, ownerQuestion: { text: "Do you have recent customer feedback we can use for the review?", choices: ["I can share a summary", "No feedback yet"] } };
  await t.mutation(internal.stepWork.finish, { workId: first.workId, result: JSON.stringify(result), sources: "[]" });
  await owner.client.mutation(api.stepWork.saveDraft, { slug, workId: first.workId, index: 0, expectedRevision: 0, body: "Keep this owner edit in the resumed work." });
  const ref = await t.query(internal.stepWork.ref, { workId: first.workId });
  await t.mutation(internal.engine.finishRun, { runId: ref!.runId, status: "verified" });
  const second = await owner.client.mutation(api.stepWork.start, { slug, strategyId, stepKey, requestKey: "answered-detail-work", answer: "I’m not sure yet" });
  const saved = await t.run(ctx => ctx.db.get(second.workId));
  expect(saved?.answers[0]).toContain(result.ownerQuestion.text);
  expect(saved?.answers[0]).toContain("I’m not sure yet");
  expect(saved?.previousWork).toContain("Keep this owner edit");
});
it("rejects cross-tenant access, viewers, stale task results and unsupported source claims", async () => {
  const { t, owner, slug, strategyId, stepKey, orgId } = await stepWorkFixture();
  const other = await asNewUser(t, "outside-work@example.com");
  await expect(other.client.query(api.stepWork.view, { slug, strategyId, stepKey })).rejects.toThrow();
  await t.run(ctx => ctx.db.insert("memberships", { orgId, userId: other.userId, role: "viewer", status: "active", createdAt: Date.now() }));
  await expect(other.client.mutation(api.stepWork.start, { slug, strategyId, stepKey, requestKey: "viewer-work-request" })).rejects.toThrow();
  const work = await owner.client.mutation(api.stepWork.start, { slug, strategyId, stepKey, requestKey: "changed-work-request" });
  await expect(t.mutation(internal.stepWork.finish, { workId: work.workId, result: JSON.stringify({ ...usefulStepResult, evidence: [{ url: "https://unsupported.example/", quote: "This is invented", claim: "A verified fact" }] }), sources: "[]" })).rejects.toThrow(/source checks/);
  await t.run(async ctx => { const plan = (await ctx.db.get(strategyId))!; await ctx.db.patch(strategyId, { expert: { ...plan.expert!, phases: plan.expert!.phases.map((phase, i) => i ? phase : { ...phase, focus: "An entirely changed instruction" }) } }); });
  expect(await t.query(internal.stepWork.load, { workId: work.workId })).toBeNull();
  expect(await t.mutation(internal.stepWork.finish, { workId: work.workId, result: JSON.stringify(usefulStepResult), sources: "[]" })).toBe(false);
});
