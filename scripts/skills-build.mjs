// Compiles skills/<id>/{SKILL.md, examples.md, rubric.md, reference/*.md} into
// shared/skills/generated.ts so agents can load playbooks inline (cached
// system blocks). Run after editing any skill: pnpm skills:build
// The same folders are published to the Anthropic Skills API by skills-publish.mjs.
import { createHash } from "node:crypto";
import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const root = "skills";
const out = "shared/skills/generated.ts";

function frontmatter(text) {
  const m = text.match(/^---\n([\s\S]*?)\n---\n?([\s\S]*)$/);
  if (!m) throw new Error("SKILL.md must start with YAML frontmatter (name, description)");
  const meta = {};
  for (const line of m[1].split("\n")) {
    const kv = line.match(/^([a-z_]+):\s*(.*)$/i);
    if (kv) meta[kv[1]] = kv[2].replace(/^["']|["']$/g, "").trim();
  }
  return { meta, body: m[2].trim() };
}

const skills = {};
for (const id of readdirSync(root).filter((d) => existsSync(join(root, d, "SKILL.md"))).sort()) {
  const dir = join(root, id);
  const { meta, body } = frontmatter(readFileSync(join(dir, "SKILL.md"), "utf8"));
  if (meta.name !== id) throw new Error(`${dir}/SKILL.md: name "${meta.name}" must equal the folder name "${id}"`);
  if (!meta.description || meta.description.length > 1024) throw new Error(`${dir}: description is required (≤1024 chars)`);
  const read = (f) => (existsSync(join(dir, f)) ? readFileSync(join(dir, f), "utf8").trim() : "");
  const refs = existsSync(join(dir, "reference"))
    ? readdirSync(join(dir, "reference")).filter((f) => f.endsWith(".md")).sort().map((f) => readFileSync(join(dir, "reference", f), "utf8").trim())
    : [];
  const examples = read("examples.md");
  const playbook = [body, ...refs, examples ? `## Examples\n\n${examples}` : ""].filter(Boolean).join("\n\n");
  const rubricRaw = read("rubric.json");
  if (!rubricRaw) throw new Error(`${dir}/rubric.json is required`);
  const rubric = JSON.parse(rubricRaw);
  if (rubric.id !== id) throw new Error(`${dir}/rubric.json: id must be "${id}"`);
  if (!rubric.gates?.length || !rubric.criteria?.length || !rubric.shipRule) throw new Error(`${dir}/rubric.json: gates, criteria and shipRule are required`);
  for (const c of rubric.criteria) if (!c.anchors?.["1"] || !c.anchors?.["3"] || !c.anchors?.["5"]) throw new Error(`${dir}/rubric.json: criterion ${c.id} needs anchors 1, 3 and 5`);
  const hash = createHash("sha256").update(playbook + "\n" + JSON.stringify(rubric)).digest("hex").slice(0, 12);
  skills[id] = { name: id, description: meta.description, playbook, rubric, hash };
}

writeFileSync(
  out,
  `// GENERATED by scripts/skills-build.mjs from skills/. Do not edit by hand.\n/* eslint-disable */\nimport type { Rubric } from "../agents/types";\nexport const SKILLS: Record<string, { name: string; description: string; playbook: string; rubric: Rubric; hash: string }> = ${JSON.stringify(skills, null, 1)};\n`,
);
console.log(`Built ${Object.keys(skills).length} skill(s) → ${out}`);
