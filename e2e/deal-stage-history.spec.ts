import { expect, test } from "@playwright/test";
import { expectAccessible, expectNoHorizontalScroll, openDemo } from "./helpers";
import { localDemoFixtures } from "./local-demo-fixtures";
const envFile = process.env.CLIMBOS_DESIGN_E2E_ENV_FILE;
const { rows, append } = localDemoFixtures(envFile);
const copyRow = ({ _id: _i, _creationTime: _c, ...data }: Record<string, unknown>) => data;

test("Stage history pages recorded changes and flags changed snapshots without sending @mobile", async ({ page, baseURL }, testInfo) => {
  test.skip(!envFile, "Requires isolated loopback fixtures");
  test.setTimeout(180_000);
  expect(baseURL).toBe("http://127.0.0.1:3420");
  const demoSlug = await openDemo(page);
  const original = (await rows("organizations")).find(row => row.slug === demoSlug);
  if (!original || original.kind !== "demo") throw new Error("Demo workspace required");
  const member = (await rows("memberships")).find(row => row.orgId === original._id);
  if (!member) throw new Error("Demo owner missing");
  const slug = `stage-history-${testInfo.project.name}-${Date.now()}`;
  await append("organizations", [{ ...copyRow(original), slug, name: "Stage history fixture", kind: "demo", currency: "USD" }]);
  const org = (await rows("organizations")).find(row => row.slug === slug);
  if (!org || org.kind !== "demo") throw new Error("Isolated workspace missing");
  await append("memberships", [{ ...copyRow(member), orgId: org._id }]);
  const now = Date.now();
  const events = Array.from({ length: 25 }, (_, i) => ({ sequence: i + 1, from: i === 0 ? null : i % 2 === 0 ? "talking" : "lead", to: i % 2 === 0 ? "lead" : "talking", source: i === 0 ? "inbound" : "owner", at: now - (25 - i) * 86400000 }));
  await append("deals", [{ orgId: org._id, name: "Workshop customer", stage: "lead", stageHistory: { total: 25, fromCreation: true, events }, source: "manual", currency: "USD", notes: [], createdAt: now, updatedAt: now }]);
  const effects = async () => Promise.all(["climbMessages", "workflowRuns", "approvals", "actionReceipts", "webhookDeliveries", "emailLog"].map(async table => (await rows(table)).filter(row => row.orgId === org._id)));
  const before = await effects(); const errors: string[] = [];
  page.on("pageerror", error => errors.push(error.message));
  await page.goto(`/app/${slug}/pipeline`);
  await page.getByRole("button", { name: /Workshop customer/ }).click();
  const sheet = page.getByRole("dialog", { name: "Workshop customer", exact: true });
  await sheet.getByText("Stage history", { exact: true }).click();
  await expect(sheet.getByText(/Showing 20 of 25 retained/)).toBeVisible();
  await sheet.getByRole("button", { name: "Earlier changes", exact: true }).click();
  await expect(sheet.getByText("Added as Possible customer", { exact: true })).toBeVisible();
  await expect(sheet.getByText(/Recorded inbound capture/)).toBeVisible();
  await sheet.getByRole("combobox").click();
  await page.getByRole("option", { name: "In conversation", exact: true }).click();
  await expect(sheet.getByText(/This deal changed\. This page is an earlier snapshot/)).toBeVisible();
  await sheet.getByRole("button", { name: "Latest history", exact: true }).click();
  await expect(sheet.getByText(/Showing 20 of 26 retained/)).toBeVisible();
  await expect(sheet.getByText(/#26 · Owner-reported change/)).toBeVisible();
  await sheet.evaluate(async el => { await Promise.all(el.getAnimations({ subtree: true }).map(animation => animation.finished.catch(() => undefined))); });
  await expectAccessible(page, "stage history");
  await expectNoHorizontalScroll(page);
  await sheet.getByText("Stage history", { exact: true }).scrollIntoViewIfNeeded();
  await page.screenshot({ path: testInfo.outputPath("stage-history.png"), fullPage: false });
  expect(await effects()).toEqual(before);
  expect(errors).toEqual([]);
});
