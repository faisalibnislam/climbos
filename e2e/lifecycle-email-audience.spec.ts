import { createHash } from "node:crypto";
import { expect, test } from "@playwright/test";
import { expectAccessible, expectNoHorizontalScroll, openDemo } from "./helpers";
import { localDemoFixtures } from "./local-demo-fixtures";

const envFile = process.env.CLIMBOS_DESIGN_E2E_ENV_FILE;
const { cli, rows, append } = localDemoFixtures(envFile);

test("owner previews dated progress eligibility and sees a completed milestone leave the audience @mobile", async ({ page, baseURL }, testInfo) => {
  test.skip(!envFile, "Requires isolated loopback fixtures"); test.setTimeout(150000);
  expect(baseURL).toBe("http://127.0.0.1:3420");
  const slug = await openDemo(page), org = (await rows("organizations")).find(row => row.slug === slug)!;
  expect(org.kind).toBe("demo");
  const member = (await rows("memberships")).find(row => row.orgId === org._id)!;
  const identity = JSON.stringify({ subject: `${member.userId}|lifecycle-fixture`, tokenIdentifier: "test|lifecycle-fixture" });
  await cli(["run", "marketing:importContacts", JSON.stringify({ slug, csv: "email,consent,consent_source,consent_date,segment\nana@example.com,yes,signup,2026-10-01,lifecycle-test\nbea@example.com,yes,signup,2026-10-01,lifecycle-test\ndee@example.com,yes,signup,2026-10-01,lifecycle-test" }), "--identity", identity]);
  const contacts = (await rows("contacts")).filter(row => row.orgId === org._id);
  const contactId = (email: string) => contacts.find(row => row.emailHash === createHash("sha256").update(email).digest("hex"))!._id;
  const progress = async (email: string, state: string, expectedRevision: number) => cli(["run", "marketing:recordContactProgress", JSON.stringify({ slug, contactId: contactId(email), expectedRevision, scope: "Export onboarding", state, criterion: "Created account; real export not yet observed", evidence: "Owner inspected the synthetic customer record", observedOn: new Date().toISOString().slice(0, 10) }), "--identity", identity]);
  await progress("ana@example.com", "started", 0);
  await progress("bea@example.com", "activated", 0);
  const artifact = (await rows("artifacts")).find(row => row.orgId === org._id && row.kind === "email_sequence")!;
  await cli(["run", "content:decide", JSON.stringify({ slug, artifactId: artifact._id, decision: "approve" }), "--identity", identity]);
  if (!(await rows("connections")).some(row => row.orgId === org._id && row.provider === "email_resend")) await append("connections", [{ orgId: org._id, provider: "email_resend", status: "connected", isFixture: true, scopes: [], accountLabel: "Local fixture without credentials", createdBy: member.userId, createdAt: Date.now(), updatedAt: Date.now() }]);
  const effects = async () => Promise.all(["approvals", "actionReceipts", "reviewRequests", "outboundSends", "emailLog", "consentRecords"].map(async table => (await rows(table)).filter(row => row.orgId === org._id)));
  const before = await effects(), errors: string[] = [];
  page.on("pageerror", error => errors.push(error.message));
  await page.goto(`/app/${slug}/content/${artifact._id}`);
  await page.getByRole("combobox", { name: "Who gets it" }).click();
  await page.getByRole("option", { name: /lifecycle-test/ }).click();
  await page.getByRole("checkbox", { name: "Limit this email by customer progress" }).check();
  const send = page.getByRole("button", { name: "Send", exact: true });
  await expect(send).toBeDisabled();
  await page.getByRole("combobox", { name: "Reported customer group" }).click();
  await page.getByRole("option", { name: /Export onboarding · Started/ }).click();
  const age = page.getByLabel("Oldest acceptable observation (days)");
  await expect(age).toHaveValue("");
  await age.fill("7");
  await expect(page.getByText("1 of 3 opted-in contacts qualify", { exact: true })).toBeVisible();
  await expect(page.getByText(/1 with different progress.*1 with missing, unknown or conflicting/)).toBeVisible();
  await expect(page.getByText(/Use a provider list that matches the filtered audience exactly/)).toBeVisible();
  await expect(send).toBeEnabled();
  await expectAccessible(page, "Lifecycle email audience preview"); await expectNoHorizontalScroll(page);
  await page.screenshot({ path: testInfo.outputPath("lifecycle-audience-preview.png"), fullPage: true });
  await progress("ana@example.com", "activated", 1);
  await expect(page.getByText("0 of 3 opted-in contacts qualify", { exact: true })).toBeVisible();
  await expect(send).toBeDisabled();
  expect(await effects()).toEqual(before); expect(errors).toEqual([]);
  await expectNoHorizontalScroll(page);
  await page.screenshot({ path: testInfo.outputPath("lifecycle-audience-exit.png"), fullPage: true });
});
