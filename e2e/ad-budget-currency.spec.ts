import { expect, test } from "@playwright/test";
import { expectAccessible, expectNoHorizontalScroll, openDemo } from "./helpers";
import { localDemoFixtures } from "./local-demo-fixtures";

const envFile = process.env.CLIMBOS_DESIGN_E2E_ENV_FILE;
const { cli, rows, append } = localDemoFixtures(envFile);
const copyRow = ({ _id: _i, _creationTime: _c, ...data }: Record<string, unknown>) => data;

test("confirms legacy currency units and prepares exact budgets without executing @mobile", async ({ page, baseURL }, testInfo) => {
  test.skip(!envFile, "Requires isolated loopback fixtures");
  test.setTimeout(150_000);
  page.setDefaultTimeout(15_000);
  expect(baseURL).toBe("http://127.0.0.1:3420");
  const demoSlug = await openDemo(page);
  const original = (await rows("organizations")).find(r => r.slug === demoSlug);
  if (!original || original.kind !== "demo") throw new Error("Demo workspace required");
  const member = (await rows("memberships")).find(r => r.orgId === original._id);
  const policy = (await rows("autonomyPolicies")).find(r => r.orgId === original._id && r.active);
  const business = (await rows("businesses")).find(r => r.orgId === original._id);
  if (!member || !policy || !business) throw new Error("Demo owner, policy and business required");
  const slug = `ad-currency-${testInfo.project.name}-${Date.now()}`;
  await append("organizations", [{ ...copyRow(original), slug, name: "Currency budget fixture", kind: "demo", currency: "KWD" }]);
  const org = (await rows("organizations")).find(r => r.slug === slug)!;
  await append("memberships", [{ ...copyRow(member), orgId: org._id }]);
  const { budgetUnitVersion: _oldVersion, ...legacyPolicy } = copyRow(policy);
  await append("autonomyPolicies", [{ ...legacyPolicy, orgId: org._id, currency: "KWD", maxMonthlyAdSpendMinor: 60000, mode: "review", version: 1 }]);
  await append("businesses", [{ ...copyRow(business), orgId: org._id, currency: "KWD" }]);
  const clonedBusiness = (await rows("businesses")).find(r => r.orgId === org._id)!;
  const now = Date.now();
  await append("artifacts", [{ orgId: org._id, businessId: clonedBusiness._id, kind: "ad", channel: "meta_ad", title: "Currency draft fixture", status: "draft", currentVersion: 0, createdAt: now, updatedAt: now }]);
  const artifact = (await rows("artifacts")).find(r => r.orgId === org._id)!;
  const identity = JSON.stringify({ subject: `${member.userId}|budget-fixture`, tokenIdentifier: "test|budget-fixture" });
  await cli(["run", "content:edit", JSON.stringify({ slug, artifactId: artifact._id, body: "Explore our services.", destinationUrl: "https://example.com/services", hashtags: [] }), "--identity", identity]);
  await cli(["run", "content:decide", JSON.stringify({ slug, artifactId: artifact._id, decision: "approve" }), "--identity", identity]);
  const errors: string[] = [];
  page.on("pageerror", error => errors.push(error.message));
  await page.goto(`/app/${slug}/content/${artifact._id}`);
  await expect(page.getByRole("button", { name: "Prepare campaign", exact: true })).toBeDisabled();
  await expect(page.getByText("Confirm the spending limit", { exact: true })).toBeVisible();
  await page.goto(`/app/${slug}/settings/policies`);
  await expect(page.getByText("Confirm your monthly budget", { exact: true })).toBeVisible();
  const budget = page.getByLabel("Maximum monthly ad spend (KWD)");
  await expect(budget).toHaveValue("");
  await expect(page.getByText(/This switch alone enables no monitors. Conversion-tracking loss is not monitored./)).toBeVisible();
  await budget.fill("100.123");
  await page.getByRole("button", { name: "Save", exact: true }).click();
  await page.getByRole("alertdialog").getByRole("button", { name: "Save and cancel approvals", exact: true }).click();
  await expect(page.getByText("Confirm your monthly budget", { exact: true })).toHaveCount(0);
  await expect(budget).toHaveValue("100.123");
  const savedPolicies = (await rows("autonomyPolicies")).filter(r => r.orgId === org._id);
  expect(savedPolicies.find(r => r.active)).toMatchObject({ currency: "KWD", maxMonthlyAdSpendMinor: 100123, budgetUnitVersion: "currency-minor-v1", version: 2 });
  expect(savedPolicies.find(r => !r.active)).toMatchObject({ maxMonthlyAdSpendMinor: 60000, version: 1 });
  await page.goto(`/app/${slug}/content/${artifact._id}`);
  await page.getByLabel("Daily budget (KWD)").fill("1.234");
  await page.getByLabel("Target cost per conversion (KWD, optional)").fill("2.345");
  await page.getByRole("button", { name: "Prepare campaign", exact: true }).click();
  const dialog = page.getByRole("alertdialog");
  await expect(dialog).toContainText("KWD 1.234/day");
  await expect(dialog).toContainText("KWD 17.276");
  await dialog.getByRole("button", { name: "Prepare campaign", exact: true }).click();
  await expect(page.getByRole("heading", { name: "Another campaign", exact: true })).toBeVisible();
  const prepared = (await rows("campaigns")).find(r => r.orgId === org._id)!;
  expect(prepared).toMatchObject({ dailyBudgetMinor: 1234, targetCostPerConversionMinor: 2345, budgetEnvelopeMinor: 17276, budgetUnitVersion: "currency-minor-v1", status: "needs_approval" });
  expect((await rows("actionReceipts")).filter(r => r.orgId === org._id)).toHaveLength(0);
  expect((await rows("approvals")).filter(r => r.orgId === org._id && r.subjectType === "campaign_activation")).toHaveLength(0);
  const { budgetUnitVersion: _version, ...legacyCampaign } = copyRow(prepared);
  await append("campaigns", [{ ...legacyCampaign, name: "Legacy currency campaign" }]);
  await page.goto(`/app/${slug}/content?tab=ads`);
  await page.getByRole("tab", { name: "Ads", exact: true }).click();
  const card = page.getByRole("article").filter({ has: page.getByRole("heading", { name: "Legacy currency campaign", exact: true }) });
  await expect(card.getByText(/stored budget units need owner review/)).toBeVisible();
  await expect(card.getByRole("button", { name: "Create paused", exact: true })).toBeDisabled();
  await expect(card.getByRole("button", { name: "Don't create", exact: true })).toBeEnabled();
  const legacy = (await rows("campaigns")).find(r => r.orgId === org._id && r.name === "Legacy currency campaign");
  expect(legacy).toMatchObject({ dailyBudgetMinor: 1234, budgetEnvelopeMinor: 17276 });
  expect(legacy?.budgetUnitVersion).toBeUndefined();
  await expect(page.getByText("Pause conditions to review:", { exact: true })).toBeVisible();
  await expect(page.getByText(/Other conditions, including tracking loss, need manual review/)).toBeVisible();
  await expectAccessible(page, "currency review states");
  await expectNoHorizontalScroll(page);
  await page.screenshot({ path: testInfo.outputPath("currency-budget-review.png"), fullPage: true });
  expect(errors).toEqual([]);
});
