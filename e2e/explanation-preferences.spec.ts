import { expect, test } from "@playwright/test";
import { expectAccessible, expectNoHorizontalScroll, openDemo } from "./helpers";
import { localDemoFixtures } from "./local-demo-fixtures";
const envFile = process.env.CLIMBOS_DESIGN_E2E_ENV_FILE;
const { rows } = localDemoFixtures(envFile);

test("Owner explanation preference persists without starting work @mobile", async ({ page, baseURL }, testInfo) => {
  test.skip(!envFile, "Requires isolated loopback fixtures");
  test.setTimeout(180_000);
  expect(baseURL).toBe("http://127.0.0.1:3420");
  const slug = await openDemo(page);
  const org = (await rows("organizations")).find(row => row.slug === slug);
  if (!org || org.kind !== "demo") throw new Error("Demo workspace required");
  const member = (await rows("memberships")).find(row => row.orgId === org._id);
  if (!member) throw new Error("Demo owner missing");
  const effects = async () => Promise.all(["climbMessages", "workflowRuns", "approvals", "actionReceipts", "webhookDeliveries", "emailLog"].map(async table => (await rows(table)).filter(row => row.orgId === org._id)));
  const before = await effects();
  const otherPreferences = (await rows("userPreferences")).filter(row => row.userId !== member.userId);
  const errors: string[] = []; page.on("pageerror", error => errors.push(error.message));
  await page.goto(`/app/${slug}/settings/profile`);
  const group = page.getByRole("radiogroup", { name: "How Climb AI explains things", exact: true });
  await group.getByRole("radio", { name: /Guided/ }).click();
  await page.getByRole("button", { name: "Save", exact: true }).click();
  await expect(page.getByText("Profile saved", { exact: true })).toBeVisible();
  await page.reload();
  await expect(group.getByRole("radio", { name: /Guided/ })).toBeChecked();
  expect((await rows("userPreferences")).find(row => row.userId === member.userId)).toMatchObject({ explanationDepth: "guided" });
  await group.getByRole("radio", { name: /Detailed/ }).click();
  await page.getByRole("button", { name: "Save", exact: true }).click();
  await expect(page.getByText("Profile saved", { exact: true })).toBeVisible();
  await page.reload();
  await expect(group.getByRole("radio", { name: /Detailed/ })).toBeChecked();
  await group.scrollIntoViewIfNeeded();
  await expectAccessible(page, "personal explanation preference");
  await expectNoHorizontalScroll(page);
  await page.screenshot({ path: testInfo.outputPath("explanation-preference.png"), fullPage: true });
  expect((await rows("userPreferences")).filter(row => row.userId !== member.userId)).toEqual(otherPreferences);
  expect(await effects()).toEqual(before);
  expect(errors).toEqual([]);
});
