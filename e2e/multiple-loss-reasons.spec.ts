import { expect, test } from "@playwright/test";
import { expectAccessible, expectNoHorizontalScroll, openDemo } from "./helpers";
import { localDemoFixtures } from "./local-demo-fixtures";
const envFile = process.env.CLIMBOS_DESIGN_E2E_ENV_FILE;
const { rows, append } = localDemoFixtures(envFile);
const copyRow = ({ _id: _i, _creationTime: _c, ...data }: Record<string, unknown>) => data;

test("Multiple reported loss reasons remain optional and do not execute actions @mobile", async ({ page, baseURL }, testInfo) => {
  test.skip(!envFile, "Requires isolated loopback fixtures");
  test.setTimeout(180_000);
  expect(baseURL).toBe("http://127.0.0.1:3420");
  const demoSlug = await openDemo(page);
  const original = (await rows("organizations")).find(row => row.slug === demoSlug);
  if (!original || original.kind !== "demo") throw new Error("Demo workspace required");
  const member = (await rows("memberships")).find(row => row.orgId === original._id);
  if (!member) throw new Error("Demo owner missing");
  const slug = `loss-reasons-${testInfo.project.name}-${Date.now()}`;
  await append("organizations", [{ ...copyRow(original), slug, name: "Loss reasons fixture", kind: "demo", currency: "USD" }]);
  const org = (await rows("organizations")).find(row => row.slug === slug);
  if (!org || org.kind !== "demo") throw new Error("Isolated workspace missing");
  await append("memberships", [{ ...copyRow(member), orgId: org._id }]);
  const now = Date.now();
  await append("deals", [{ orgId: org._id, name: "Workshop customer", stage: "lost", lostAt: now, lostReason: "price", source: "manual", currency: "USD", notes: [], createdAt: now, updatedAt: now }]);
  const effects = async () => Promise.all(["climbMessages", "workflowRuns", "approvals", "actionReceipts", "webhookDeliveries", "emailLog"].map(async table => (await rows(table)).filter(row => row.orgId === org._id)));
  const before = await effects(); const errors: string[] = [];
  page.on("pageerror", error => errors.push(error.message));
  await page.goto(`/app/${slug}/pipeline`);
  await page.getByRole("button", { name: /Workshop customer/ }).click();
  const sheet = page.getByRole("dialog", { name: "Workshop customer", exact: true });
  const reasons = sheet.getByRole("region", { name: "Loss reasons", exact: true });
  await reasons.getByRole("button", { name: "Edit loss reasons", exact: true }).click();
  await expect(reasons.getByRole("checkbox", { name: "Price or budget", exact: true })).toBeChecked();
  await reasons.getByRole("checkbox", { name: "Timing", exact: true }).check();
  await reasons.getByLabel("Owner’s context (optional)").fill("Budget was tight and the launch was postponed; reported by owner.");
  await sheet.evaluate(async el => { await Promise.all(el.getAnimations({ subtree: true }).map(animation => animation.finished.catch(() => undefined))); });
  await expectAccessible(page, "multiple loss reason entry");
  await expectNoHorizontalScroll(page);
  await page.screenshot({ path: testInfo.outputPath("loss-reasons.png"), fullPage: false });
  await reasons.getByRole("button", { name: "Save loss reasons", exact: true }).click();
  await expect(reasons.getByText("Price or budget · Timing", { exact: true })).toBeVisible();
  let saved = (await rows("deals")).find(row => row.orgId === org._id);
  expect(saved).toMatchObject({ stage: "lost", lostReasons: ["price", "timing"] });
  expect(saved).not.toHaveProperty("lostReason");
  await reasons.getByRole("button", { name: "Edit loss reasons", exact: true }).click();
  await reasons.getByRole("checkbox", { name: "Price or budget", exact: true }).uncheck();
  await reasons.getByRole("checkbox", { name: "Timing", exact: true }).uncheck();
  await reasons.getByLabel("Owner’s context (optional)").fill("");
  await reasons.getByRole("button", { name: "Save loss reasons", exact: true }).click();
  await expect(reasons.getByText("No reasons recorded", { exact: true })).toBeVisible();
  saved = (await rows("deals")).find(row => row.orgId === org._id);
  expect(saved).toMatchObject({ stage: "lost", lostReasons: [] });
  expect(await effects()).toEqual(before);
  expect(errors).toEqual([]);
});
