import { expect, test } from "@playwright/test";
import { expectAccessible, expectNoHorizontalScroll, openDemo } from "./helpers";
import { localDemoFixtures } from "./local-demo-fixtures";

const envFile = process.env.CLIMBOS_DESIGN_E2E_ENV_FILE;
const { rows, append } = localDemoFixtures(envFile);
const copyRow = (row: Record<string, unknown>) => Object.fromEntries(Object.entries(row).filter(([key]) => key !== "_id" && key !== "_creationTime"));

test("owner can inspect, correct, dismiss and restore customer themes without executing actions @mobile", async ({ page, baseURL }, testInfo) => {
  test.skip(!envFile, "Requires explicitly configured isolated loopback fixtures");
  test.setTimeout(150_000);
  expect(baseURL).toBe("http://127.0.0.1:3420");
  const demoSlug = await openDemo(page);
  const original = (await rows("organizations")).find(row => row.slug === demoSlug);
  if (!original || original.kind !== "demo") throw new Error("Isolated demo required");
  const member = (await rows("memberships")).find(row => row.orgId === original._id);
  const business = (await rows("businesses")).find(row => row.orgId === original._id);
  if (!member || !business) throw new Error("Demo records required");
  const slug = `voice-learning-${testInfo.project.name}-${Date.now()}`;
  await append("organizations", [{ ...copyRow(original), slug, name: "Synthetic customer voice" }]);
  const org = (await rows("organizations")).find(row => row.slug === slug)!;
  await append("memberships", [{ ...copyRow(member), orgId: org._id }]);
  await append("businesses", [{ ...copyRow(business), orgId: org._id }]);
  const now = Date.now();
  await append("communityMessages", [0, 1].map(index => ({ orgId: org._id, channel: "google", kind: "review", externalId: `review:synthetic-${index}`, authorName: "Private Person", text: "Synthetic setup feedback from Private Person at private@example.com", receivedAt: now - index, status: "new", createdAt: now, updatedAt: now, reviewSourceUrl: `https://reviews.example/synthetic/${index}` })));
  const snapshot = async () => Promise.all(["artifacts", "approvals", "actionReceipts", "workflowRuns"].map(async table => (await rows(table)).filter(row => row.orgId === org._id)));
  const before = await snapshot();
  await page.goto(`/app/${slug}/reviews`);
  const heading = page.getByRole("heading", { name: "Possible customer themes" });
  await expect(heading).toBeVisible();
  const card = heading.locator("../..");
  await expect(card).toContainText("2 matching records");
  await expect(card).toContainText("Owner-entered records");
  await expect(card).not.toContainText("private@example.com");
  await card.getByRole("combobox", { name: "Correct theme Getting started" }).click();
  await page.getByRole("option", { name: "Reliability", exact: true }).click();
  await card.getByRole("textbox", { name: "Correction note for Getting started" }).fill("Investigate errors rather than onboarding instructions.");
  await card.getByRole("button", { name: "Correct", exact: true }).click();
  await expect(card.getByText("Owner correction", { exact: true })).toBeVisible();
  await expect(card).toContainText("Owner interpretation, not independent verification.");
  await card.getByText("How this works", { exact: true }).click();
  await expect(card).toContainText("not unique customers");
  await expect(card).toContainText("dismissed themes are excluded");
  await expectNoHorizontalScroll(page);
  await expectAccessible(page, "Customer voice review");
  await card.screenshot({ path: testInfo.outputPath("customer-voice.png") });
  await card.getByRole("button", { name: "Dismiss", exact: true }).click();
  await expect(card.getByText("Dismissed", { exact: true })).toBeVisible();
  const feedback = (await rows("voiceThemeFeedback")).filter(row => row.orgId === org._id);
  expect(feedback).toMatchObject([{ status: "dismissed", themeKey: "onboarding" }]);
  await card.getByRole("button", { name: "Restore", exact: true }).click();
  await expect(card.getByText("Getting started", { exact: true }).first()).toBeVisible();
  expect((await rows("voiceThemeFeedback")).filter(row => row.orgId === org._id)).toEqual([]);
  expect((await rows("auditEvents")).filter(row => row.orgId === org._id && String(row.action).startsWith("reviews.voice_theme"))).toHaveLength(3);
  expect(await snapshot()).toEqual(before);
});
