import { expect, test } from "@playwright/test";
import { expectAccessible, expectNoHorizontalScroll, openDemo } from "./helpers";
import { localDemoFixtures } from "./local-demo-fixtures";
const envFile = process.env.CLIMBOS_DESIGN_E2E_ENV_FILE;
const { rows, append } = localDemoFixtures(envFile);
const copyRow = ({ _id: _i, _creationTime: _c, ...data }: Record<string, unknown>) => data;
test.use({ timezoneId: "Pacific/Honolulu" });

test("Next-step calendar date survives save and reopen across browser and workspace timezones @mobile", async ({ page, baseURL }, testInfo) => {
  test.skip(!envFile, "Requires isolated loopback fixtures");
  test.setTimeout(180_000);
  expect(baseURL).toBe("http://127.0.0.1:3420");
  const demoSlug = await openDemo(page);
  const original = (await rows("organizations")).find(row => row.slug === demoSlug);
  if (!original || original.kind !== "demo") throw new Error("Demo workspace required");
  const member = (await rows("memberships")).find(row => row.orgId === original._id);
  if (!member) throw new Error("Demo owner missing");
  const slug = `pipeline-dates-${testInfo.project.name}-${Date.now()}`;
  await append("organizations", [{ ...copyRow(original), slug, name: "Follow-up date fixture", timezone: "Asia/Dhaka", kind: "demo", currency: "USD" }]);
  const org = (await rows("organizations")).find(row => row.slug === slug);
  if (!org || org.kind !== "demo") throw new Error("Isolated workspace missing");
  await append("memberships", [{ ...copyRow(member), orgId: org._id }]);
  const now = Date.now();
  await append("deals", [{ orgId: org._id, name: "Calendar customer", stage: "talking", source: "manual", currency: "USD", notes: [], nextStep: "Review proposal", nextStepDate: "2026-01-15", stageChangedAt: now, createdAt: now, updatedAt: now }]);
  const deal = (await rows("deals")).find(row => row.orgId === org._id)!;
  const effects = async () => Promise.all(["climbMessages", "workflowRuns", "approvals", "actionReceipts", "webhookDeliveries", "bookings", "emailLog"].map(async table => (await rows(table)).filter(row => row.orgId === org._id)));
  const before = await effects(); const errors: string[] = [];
  page.on("pageerror", error => errors.push(error.message));
  await page.goto(`/app/${slug}/pipeline`);
  await expect(page.getByText(/Next-step dates use Asia\/Dhaka/)).toBeVisible();
  await expect(page.getByText("Next step overdue", { exact: true })).toBeVisible();
  await page.getByRole("button", { name: /Calendar customer/ }).click();
  const sheet = page.getByRole("dialog", { name: "Calendar customer", exact: true });
  const date = sheet.locator("#pipeline-next-step-date");
  await expect(date).toContainText("Jan 15, 2026");
  await date.click();
  await page.getByRole("gridcell", { name: "Tuesday, January 20, 2026", exact: true }).click();
  await expect(date).toContainText("Jan 20, 2026");
  expect((await rows("deals")).find(row => row._id === deal._id)).toMatchObject({ nextStepDate: "2026-01-20", stageChangedAt: now });
  await page.reload();
  await page.getByRole("button", { name: /Calendar customer/ }).click();
  await expect(date).toContainText("Jan 20, 2026");
  await sheet.evaluate(async el => { await Promise.all(el.getAnimations({ subtree: true }).map(animation => animation.finished.catch(() => undefined))); });
  await expectAccessible(page, "workspace calendar date");
  await expectNoHorizontalScroll(page);
  await page.screenshot({ path: testInfo.outputPath("pipeline-date.png"), fullPage: true });
  await sheet.getByRole("button", { name: "Clear next-step date", exact: true }).click();
  await expect(date).toContainText("Pick a date");
  const after = (await rows("deals")).find(row => row._id === deal._id)!;
  expect(after.nextStepAt).toBeUndefined(); expect(after.nextStepDate).toBeUndefined();
  expect(after.stageChangedAt).toBe(now);
  expect(await effects()).toEqual(before);
  expect(errors).toEqual([]);
});
