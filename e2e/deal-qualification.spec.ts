import { expect, test } from "@playwright/test";
import { expectAccessible, expectNoHorizontalScroll, openDemo, pickCalendarDate } from "./helpers";
import { localDemoFixtures } from "./local-demo-fixtures";
const envFile = process.env.CLIMBOS_DESIGN_E2E_ENV_FILE;
const { rows, append } = localDemoFixtures(envFile);
const copyRow = ({ _id: _i, _creationTime: _c, ...data }: Record<string, unknown>) => data;

test("Buying context saves dated reports and prepares review without contacting anyone @mobile", async ({ page, baseURL }, testInfo) => {
  test.skip(!envFile, "Requires isolated loopback fixtures");
  test.setTimeout(180_000);
  expect(baseURL).toBe("http://127.0.0.1:3420");
  const demoSlug = await openDemo(page);
  const original = (await rows("organizations")).find(row => row.slug === demoSlug);
  if (!original || original.kind !== "demo") throw new Error("Demo workspace required");
  const member = (await rows("memberships")).find(row => row.orgId === original._id);
  if (!member) throw new Error("Demo owner missing");
  const slug = `buying-context-${testInfo.project.name}-${Date.now()}`;
  await append("organizations", [{ ...copyRow(original), slug, name: "Buying context fixture", kind: "demo", currency: "USD" }]);
  const org = (await rows("organizations")).find(row => row.slug === slug);
  if (!org || org.kind !== "demo") throw new Error("Isolated workspace missing");
  await append("memberships", [{ ...copyRow(member), orgId: org._id }]);
  const now = Date.now();
  await append("deals", [{ orgId: org._id, name: "Workshop customer", stage: "talking", source: "manual", currency: "USD", notes: [], createdAt: now, updatedAt: now }]);
  const effects = async () => Promise.all(["climbMessages", "workflowRuns", "approvals", "actionReceipts", "webhookDeliveries", "emailLog"].map(async table => (await rows(table)).filter(row => row.orgId === org._id)));
  const before = await effects(); const errors: string[] = [];
  page.on("pageerror", error => errors.push(error.message));
  await page.goto(`/app/${slug}/pipeline`);
  await page.getByRole("button", { name: /Workshop customer/ }).click();
  const sheet = page.getByRole("dialog", { name: "Workshop customer", exact: true });
  await sheet.getByText("Buying context", { exact: true }).click();
  const need = sheet.getByRole("region", { name: "Problem to solve", exact: true });
  await expect(need.getByText("Unknown", { exact: true })).toBeVisible();
  await need.getByRole("button", { name: "Add observation" }).click();
  await need.getByRole("combobox").click();
  await page.getByRole("option", { name: "Reported", exact: true }).click();
  await need.getByLabel("What is known or needs checking?").fill("Customer wants one shared reporting process for regional teams.");
  await need.getByLabel("Where did this come from?").fill("Owner notes from the discovery call");
  await pickCalendarDate(page, need.getByLabel("Observation date", { exact: true }), "2026-01-12");
  await expectAccessible(page, "buying context entry");
  await need.getByRole("button", { name: "Save observation" }).click();
  await expect(need.getByRole("button", { name: "Update", exact: true })).toBeVisible();
  await expect(need.getByText(/Owner report · observed 2026-01-12/)).toBeVisible();
  await need.getByRole("button", { name: "Update", exact: true }).click();
  await need.getByRole("combobox").click();
  await page.getByRole("option", { name: "Conflicting reports", exact: true }).click();
  await need.getByLabel("What is known or needs checking?").fill("The regional manager says the current process is sufficient; needs clarification.");
  await need.getByRole("button", { name: "Save observation" }).click();
  await expect(need.getByRole("button", { name: "Update", exact: true })).toBeVisible();
  await sheet.getByText("Observation history (2 of 2)", { exact: true }).click();
  await expect(sheet.getByText(/Customer wants one shared reporting process for regional teams\./)).toBeVisible();
  await sheet.evaluate(async el => { await Promise.all(el.getAnimations({ subtree: true }).map(animation => animation.finished.catch(() => undefined))); });
  await expectAccessible(page, "buying context review");
  await expectNoHorizontalScroll(page);
  await expect(page.getByText("Observation saved", { exact: true })).toHaveCount(0);
  await sheet.getByText("Buying context", { exact: true }).scrollIntoViewIfNeeded();
  await page.screenshot({ path: testInfo.outputPath("buying-context.png"), fullPage: false });
  await sheet.getByRole("button", { name: "Review next step", exact: true }).click();
  const composer = page.getByRole("textbox", { name: "Message Climb AI", exact: true });
  await expect(composer).toHaveValue(/saved notes, buying context/);
  await expect(composer).toBeEditable();
  const saved = (await rows("deals")).find(row => row.orgId === org._id);
  expect(saved?.stage).toBe("talking");
  expect(saved?.qualification).toMatchObject({ revision: 2, current: [{ topic: "need", state: "conflicting" }], history: [expect.objectContaining({ state: "reported" }), expect.objectContaining({ state: "conflicting" })] });
  expect(await effects()).toEqual(before);
  expect(errors).toEqual([]);
});
