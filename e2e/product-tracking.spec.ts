import { test, expect } from "@playwright/test";
import { openDemo, expectAccessible, expectNoHorizontalScroll } from "./helpers";
import { localDemoFixtures } from "./local-demo-fixtures";

const envFile = process.env.CLIMBOS_DESIGN_E2E_ENV_FILE;
const { cli, rows } = localDemoFixtures(envFile);

test("owner connects product milestones, sees attributed progress and revokes server access without actions @mobile", async ({ page, baseURL, request }, testInfo) => {
  test.skip(!envFile, "Requires isolated loopback fixtures"); test.setTimeout(180000);
  expect(baseURL).toBe("http://127.0.0.1:3420");
  const slug = await openDemo(page), org = (await rows("organizations")).find(r => r.slug === slug)!;
  const member = (await rows("memberships")).find(r => r.orgId === org._id)!;
  const identity = JSON.stringify({ subject: `${member.userId}|event-fixture`, tokenIdentifier: "test|event-fixture" });
  await cli(["run", "marketing:importContacts", JSON.stringify({ slug, csv: "email,segment\ntracking@example.com,product-tracking-test" }), "--identity", identity]);
  const effects = async () => Promise.all(["approvals", "actionReceipts", "emailLog", "consentRecords", "workflowRuns"].map(async table => (await rows(table)).filter(r => r.orgId === org._id)));
  const before = await effects(), errors: string[] = []; page.on("pageerror", e => errors.push(e.message));
  await page.goto(`/app/${slug}/customers`);
  await page.getByRole("tab", { name: "Product tracking", exact: true }).click();
  await page.getByRole("button", { name: "Connect product events", exact: true }).click();
  const form = page.getByRole("form", { name: "Connect product events" });
  await form.getByLabel("Source name", { exact: true }).fill("Synthetic product server");
  await form.getByLabel("Product or journey", { exact: true }).fill("Real export onboarding");
  await form.getByLabel("Event name 1", { exact: true }).fill("real_export");
  await expect(form.getByRole("button", { name: "Create source and server key" })).toBeDisabled();
  await form.getByLabel("Progress meaning 1", { exact: true }).click();
  await page.getByRole("option", { name: "Reached first value", exact: true }).click();
  await form.getByLabel("Definition 1", { exact: true }).fill("Completed a real document export");
  await form.getByRole("button", { name: "Create source and server key" }).click();
  const keyField = page.getByLabel("New product tracking key", { exact: true });
  await expect(keyField).toBeVisible(); const token = await keyField.inputValue();
  expect(token.startsWith("climb_events_")).toBe(true);
  await page.getByRole("button", { name: "I saved the key", exact: true }).click();
  await expect(keyField).toHaveCount(0);
  await page.getByText("Setup instructions and limits", { exact: true }).click();
  const endpoint = await page.getByLabel("Product event endpoint", { exact: true }).inputValue();
  expect(endpoint).toBe("http://127.0.0.1:3321/product-events");
  const data = { eventId: "browser-fixture-1", email: "tracking@example.com", event: "real_export", occurredAt: new Date(Date.now() - 1000).toISOString() };
  const send = () => request.post(endpoint, { headers: { authorization: `Bearer ${token}` }, data });
  expect((await send()).status()).toBe(200);
  await expect(page.getByText("Synthetic product server · real_export · Progress updated", { exact: true })).toBeVisible();
  await page.getByRole("button", { name: "Customer progress", exact: true }).click();
  const dialog = page.getByRole("dialog", { name: "Customer progress", exact: true });
  await dialog.getByLabel("Contact email", { exact: true }).fill("tracking@example.com");
  await dialog.getByRole("button", { name: "Look up", exact: true }).click();
  await expect(dialog.getByText(/Source-reported by Synthetic product server/)).toBeVisible();
  await expect(dialog.getByText("Real export onboarding: Reached first value", { exact: true })).toBeVisible();
  await dialog.evaluate(async element => { await Promise.all(element.getAnimations({ subtree: true }).map(a => a.finished.catch(() => undefined))); });
  await expectAccessible(page, "Product tracking"); await expectNoHorizontalScroll(page);
  await page.keyboard.press("Escape");
  await page.getByText("Manage server access", { exact: true }).click();
  await page.getByRole("button", { name: "Revoke Synthetic product server", exact: true }).click();
  await expect(page.getByText(/^Revoked\. Last recorded receipt/)).toBeVisible();
  expect((await send()).status()).toBe(401);
  await expectAccessible(page, "Product tracking"); await expectNoHorizontalScroll(page);
  await expect(page.getByText("Something went wrong", { exact: true })).toHaveCount(0);
  await page.screenshot({ path: testInfo.outputPath("product-tracking.png"), fullPage: true });
  expect(await effects()).toEqual(before); expect(errors).toEqual([]);
});
