import { expect, test } from "@playwright/test";
import { expectAccessible, expectNoHorizontalScroll, openDemo } from "./helpers";
import { localDemoFixtures } from "./local-demo-fixtures";
const envFile = process.env.CLIMBOS_DESIGN_E2E_ENV_FILE;
const { rows, append } = localDemoFixtures(envFile);
const copyRow = ({ _id: _i, _creationTime: _c, ...data }: Record<string, unknown>) => data;

test("Selected deal review prepares a question without submitting or changing the deal @mobile", async ({ page, baseURL }, testInfo) => {
  test.skip(!envFile, "Requires isolated loopback fixtures");
  test.setTimeout(180_000);
  expect(baseURL).toBe("http://127.0.0.1:3420");
  const demoSlug = await openDemo(page);
  const original = (await rows("organizations")).find(row => row.slug === demoSlug);
  if (!original || original.kind !== "demo") throw new Error("Demo workspace required");
  const member = (await rows("memberships")).find(row => row.orgId === original._id);
  if (!member) throw new Error("Demo owner missing");
  const slug = `deal-review-${testInfo.project.name}-${Date.now()}`;
  await append("organizations", [{ ...copyRow(original), slug, name: "Deal review fixture", kind: "demo", currency: "USD" }]);
  const org = (await rows("organizations")).find(row => row.slug === slug);
  if (!org || org.kind !== "demo") throw new Error("Isolated workspace missing");
  await append("memberships", [{ ...copyRow(member), orgId: org._id }]);
  const now = Date.now();
  await append("deals", [{ orgId: org._id, name: "Workshop customer", stage: "talking", source: "manual", currency: "USD", notes: [{ text: "Interested in a team workshop; timing is not agreed.", at: now }], createdAt: now, updatedAt: now }]);
  const effects = async () => Promise.all(["deals", "climbMessages", "workflowRuns", "approvals", "actionReceipts", "webhookDeliveries"].map(async table => (await rows(table)).filter(row => row.orgId === org._id)));
  const before = await effects(); const errors: string[] = [];
  page.on("pageerror", error => errors.push(error.message));
  await page.goto(`/app/${slug}/pipeline`);
  await page.getByRole("button", { name: /Workshop customer/ }).click();
  const sheet = page.getByRole("dialog", { name: "Workshop customer", exact: true });
  await expect(sheet.getByText("Interested in a team workshop; timing is not agreed.", { exact: true })).toBeVisible();
  await sheet.evaluate(async el => { await Promise.all(el.getAnimations({ subtree: true }).map(animation => animation.finished.catch(() => undefined))); });
  await expectAccessible(page, "selected deal review");
  await expectNoHorizontalScroll(page);
  await page.screenshot({ path: testInfo.outputPath("deal-review.png"), fullPage: true });
  await sheet.getByRole("button", { name: "Review next step", exact: true }).click();
  await expect(sheet).not.toBeVisible();
  const composer = page.getByRole("textbox", { name: "Message Climb AI", exact: true });
  await expect(composer).toHaveValue(/Review this customer's saved notes/);
  await expect(composer).toBeEditable();
  await composer.fill("Keep my question about whether this is a good fit.");
  await page.getByRole("button", { name: "Close Climb AI", exact: true }).click();
  await page.getByRole("button", { name: /Workshop customer/ }).click();
  await sheet.getByRole("button", { name: "Review next step", exact: true }).click();
  await expect(composer).toHaveValue(/^Keep my question about whether this is a good fit\.\nReview this customer's saved notes/);
  await expectAccessible(page, "editable deal review question");
  await expectNoHorizontalScroll(page);
  await page.screenshot({ path: testInfo.outputPath("deal-review-question.png"), fullPage: true });
  expect(await effects()).toEqual(before);
  expect(errors).toEqual([]);
});
