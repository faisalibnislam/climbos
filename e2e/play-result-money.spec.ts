import { expect, test } from "@playwright/test";
import { readExpertPlan } from "../shared/agents/planCompatibility";
import { expectAccessible, expectNoHorizontalScroll, openDemo } from "./helpers";
import { localDemoFixtures } from "./local-demo-fixtures";

const envFile = process.env.CLIMBOS_DESIGN_E2E_ENV_FILE;
const { cli, rows, append } = localDemoFixtures(envFile);
const copyRow = ({ _id: _i, _creationTime: _c, ...data }: Record<string, unknown>) => data;

test("weekly reports require explicit values and preserve currency across settings changes @mobile", async ({ page, baseURL }, testInfo) => {
  test.skip(!envFile, "Requires explicitly configured isolated loopback fixtures");
  test.setTimeout(150_000);
  expect(baseURL).toBe("http://127.0.0.1:3420");
  const demoSlug = await openDemo(page);
  const original = (await rows("organizations")).find(r => r.slug === demoSlug);
  if (!original || original.kind !== "demo") throw new Error("Isolated demo required");
  const member = (await rows("memberships")).find(r => r.orgId === original._id);
  const business = (await rows("businesses")).find(r => r.orgId === original._id);
  const goal = (await rows("goals")).find(r => r.orgId === original._id && r.status === "active");
  const plan = (await rows("strategies")).find(r => r.orgId === original._id);
  const policy = (await rows("autonomyPolicies")).find(r => r.orgId === original._id && r.active);
  if (!member || !business || !goal || !plan || !policy) throw new Error("Demo plan, owner and business required");
  const slug = `weekly-money-${testInfo.project.name}-${Date.now()}`;
  await append("organizations", [{ ...copyRow(original), slug, name: "Weekly money fixture", currency: "KWD" }]);
  const org = (await rows("organizations")).find(r => r.slug === slug)!;
  await append("memberships", [{ ...copyRow(member), orgId: org._id }]);
  await append("businesses", [{ ...copyRow(business), orgId: org._id, currency: "KWD" }]);
  const savedBusiness = (await rows("businesses")).find(r => r.orgId === org._id)!;
  await append("goals", [{ ...copyRow(goal), orgId: org._id }]);
  const savedGoal = (await rows("goals")).find(r => r.orgId === org._id)!;
  await append("autonomyPolicies", [{ ...copyRow(policy), orgId: org._id, currency: "KWD" }]);
  const sourceExpert = readExpertPlan(plan.expert as Record<string, unknown>);
  // This test exercises detailed-plan reporting independently of the focused demo seed.
  const sourcePlay = { kind: "research", oneLiner: "Synthetic weekly reporting example", firstActionToday: "Record the synthetic observation." };
  const { growthPlanV9: _v9, growthPlanV8: _v8, snapshot: _snapshot, quality: _quality, ...expert } = sourceExpert;
  await append("strategies", [{ ...copyRow(plan), _creationTime: Date.now() - 21 * 86400000, orgId: org._id, businessId: savedBusiness._id, goalId: savedGoal._id, runId: undefined, approvalId: undefined, status: "approved", expert: { ...expert, version: 7, plays: [{ ...sourcePlay, id: "weekly-fixture", name: "Weekly reporting fixture", p10: undefined, p50: undefined, p90: undefined, model: { weeklyReach: 100, steps: [{ name: "Paying customers", rate: 0.1 }], monthlySpendUsd: 0, ownerHoursPerWeek: 1 } }] } }]);
  const savedPlan = (await rows("strategies")).find(r => r.orgId === org._id)!;
  const actionSnapshot = async () => Promise.all(["approvals", "actionReceipts", "workflowRuns"].map(async table => (await rows(table)).filter(r => r.orgId === org._id)));
  const before = await actionSnapshot();
  const errors: string[] = [];
  page.on("pageerror", error => errors.push(error.message));
  await page.goto(`/app/${slug}/plan`);
  await page.getByRole("tab", { name: "Research", exact: true }).click();
  await page.getByRole("button", { name: "Open research and plan details", exact: true }).click();
  await page.locator("summary").filter({ hasText: "Other ideas, numbers and questions" }).click();
  const card = page.getByRole("article").filter({ has: page.getByRole("heading", { name: "Weekly reporting fixture", exact: true }) });
  await expect(card.getByText(/3 reporting weeks are missing/)).toBeVisible();
  await card.getByRole("button", { name: "Log this week", exact: true }).click();
  await card.getByLabel("Reached", { exact: true }).fill("100");
  await expect(card.getByRole("button", { name: "Save", exact: true })).toBeDisabled();
  await card.getByLabel("Paying customers", { exact: true }).fill("10");
  await card.getByLabel("Spent (KWD)", { exact: true }).fill("12.345");
  await expect(card.getByRole("button", { name: "Save", exact: true })).toBeDisabled();
  expect((await rows("playResults")).filter(r => r.orgId === org._id)).toEqual([]);
  await card.getByLabel("Your hours", { exact: true }).fill("1");
  await card.getByLabel("Net retained revenue (KWD)", { exact: true }).fill("9.876");
  await card.getByRole("button", { name: "Save", exact: true }).click();
  await expect(card.getByRole("button", { name: "Log this week", exact: true })).toBeVisible();
  const saved = (await rows("playResults")).filter(r => r.orgId === org._id);
  expect(saved).toHaveLength(1);
  expect(saved[0]).toMatchObject({ spendUsd: 12.345, spendCurrency: "KWD", retainedRevenueMinor: 9876, retentionCurrency: "KWD", steps: [10], ownerHours: 1 });
  await expect(card.getByText(/Net retained revenue:/)).toContainText("9.876");
  await expect(card.getByText("Weekly log incomplete", { exact: true })).toBeVisible();
  await expect(card.getByText(/^Original forecast unavailable\. Record the missing inputs/)).toBeVisible();
  await expect(card).not.toContainText("NaN");
  await expect(card).not.toContainText("plan ≈0");
  await card.getByRole("button", { name: "Log this week", exact: true }).click();
  await card.getByLabel("Reached", { exact: true }).fill("100");
  await card.getByLabel("Paying customers", { exact: true }).fill("10");
  await card.getByLabel("Spent (KWD)", { exact: true }).fill("0");
  await card.getByLabel("Your hours", { exact: true }).fill("0");
  await expect(card.getByRole("button", { name: "Save", exact: true })).toBeEnabled();
  const identity = JSON.stringify({ subject: `${member.userId}|weekly-fixture`, tokenIdentifier: "test|weekly-fixture" });
  await cli(["run", "orgs:saveBusinessDetails", JSON.stringify({ slug, currency: "USD" }), "--identity", identity]);
  await expect(card.getByRole("alert")).toContainText("business currency changed");
  await expect(card.getByRole("button", { name: "Save", exact: true })).toBeDisabled();
  await expect(card.getByText(/Cash cost per customer is unavailable/)).toBeVisible();
  expect((await rows("playResults")).filter(r => r.orgId === org._id)).toEqual(saved);
  await card.getByRole("button", { name: "Cancel", exact: true }).click();
  // Historical report entry and stale editor protection use the existing UI.
  await card.getByRole("button", { name: "Log this week", exact: true }).click();
  const historicalDate = new Date(Date.now() - 7 * 86400000).toISOString().slice(0, 10);
  await card.getByRole("button", { name: "Week containing (UTC)", exact: true }).click();
  if (!(await page.locator(`[data-iso="${historicalDate}"]`).count())) await page.getByRole("button", { name: "Previous month", exact: true }).click();
  await page.locator(`[data-iso="${historicalDate}"]`).click();
  await expect(card.getByLabel("Reached", { exact: true })).toHaveValue("");
  await card.getByLabel("Reached", { exact: true }).fill("80");
  await card.getByLabel("Paying customers", { exact: true }).fill("8");
  await card.getByLabel("Spent (USD)", { exact: true }).fill("5.25");
  await card.getByLabel("Your hours", { exact: true }).fill("2");
  await card.getByRole("button", { name: "Save", exact: true }).click();
  await expect(card.getByRole("button", { name: "Log this week", exact: true })).toBeVisible();
  const historical = (await rows("playResults")).filter(r => r.orgId === org._id).find(r => r._id !== saved[0]._id)!;
  expect(historical).toMatchObject({ reach: 80, spendUsd: 5.25, spendCurrency: "USD", revision: 1 });
  await card.getByRole("button", { name: "Log this week", exact: true }).click();
  await card.getByRole("button", { name: "Week containing (UTC)", exact: true }).click();
  if (!(await page.locator(`[data-iso="${historicalDate}"]`).count())) await page.getByRole("button", { name: "Previous month", exact: true }).click();
  await page.locator(`[data-iso="${historicalDate}"]`).click();
  await expect(card.getByLabel("Reached", { exact: true })).toHaveValue("80");
  await card.getByLabel("Reached", { exact: true }).fill("90");
  await cli(["run", "playResults:log", JSON.stringify({ slug, strategyId: savedPlan._id, playName: "Weekly reporting fixture", weekStart: historical.weekStart, expectedResultId: historical._id, expectedRevision: 1, expectedWorkspaceCurrency: "USD", reach: 85, steps: [8], spendUsd: 5.25, currency: "USD", ownerHours: 2 }), "--identity", identity]);
  await expect(card.getByRole("alert")).toContainText("changed in another edit");
  await expect(card.getByLabel("Reached", { exact: true })).toHaveValue("90");
  await expect(card.getByRole("button", { name: "Save", exact: true })).toBeDisabled();
  await card.getByRole("button", { name: "Reload saved report" }).click();
  await expect(card.getByLabel("Reached", { exact: true })).toHaveValue("85");
  await card.getByLabel("Reached", { exact: true }).fill("95");
  await card.getByRole("button", { name: "Save", exact: true }).click();
  await expect(card.getByRole("button", { name: "Log this week", exact: true })).toBeVisible();
  await card.getByRole("button", { name: "Log this week", exact: true }).click();
  await card.getByRole("button", { name: "Week containing (UTC)", exact: true }).click();
  if (!(await page.locator(`[data-iso="${historicalDate}"]`).count())) await page.getByRole("button", { name: "Previous month", exact: true }).click();
  await page.locator(`[data-iso="${historicalDate}"]`).click();
  await expect(card.getByLabel("Reached", { exact: true })).toHaveValue("95");
  await card.locator("summary").filter({ hasText: "Weekly report history" }).click();
  await expect(card.getByText("Revision 3 · Current · correction", { exact: true })).toBeVisible();
  await expect(card.getByText(/Reached 80/)).toBeVisible();
  await expect(card.getByText(/Reached 85/)).toBeVisible();
  expect((await rows("playResults")).filter(r => r.orgId === org._id)).toHaveLength(2);
  await expect(page.getByRole("status").filter({ hasText: "Results saved" }).last()).toHaveCSS("opacity", "1");
  await expectNoHorizontalScroll(page);
  await expectAccessible(page, "weekly money evidence");
  await card.scrollIntoViewIfNeeded();
  await page.screenshot({ path: testInfo.outputPath("weekly-money-evidence.png"), fullPage: false });
  await append("playResults", [copyRow(historical)]);
  await expect(card.getByRole("alert").filter({ hasText: /^Conflicting reports/ })).toBeVisible();
  await expect(card.getByText(/Weekly summary unavailable/)).toBeVisible();
  await expect(card.getByText(/Cash cost per customer:/)).toHaveCount(0);
  await card.getByText(/Weekly summary unavailable/).scrollIntoViewIfNeeded();
  await expectNoHorizontalScroll(page);
  await expectAccessible(page, "weekly summary unavailable");
  await page.screenshot({ path: testInfo.outputPath("weekly-summary-unavailable.png"), fullPage: false });
  await expect(card.getByRole("button", { name: "Save", exact: true })).toHaveCount(0);

  // A separate saved plan demonstrates the decision path without changing the report-history fixture.
  const now = Date.now(), d = new Date(now);
  const currentWeek = Date.UTC(d.getUTCFullYear(), d.getUTCMonth(), d.getUTCDate()) - ((d.getUTCDay() + 6) % 7) * 86400000;
  const reviewPlays = ["Delivery review fixture", "Execution review fixture"].map((name, i) => ({ ...sourcePlay, id: `decision-${i}`, name, horizonDays: 21, p10: 270, p50: 300, p90: 330, killIf: "Review complaints before continuing", model: { weeklyReach: 1000, steps: [{ name: "Paying customers", rate: 0.1 }], monthlySpendUsd: 100, ownerHoursPerWeek: 1 } }));
  await append("strategies", [{ ...copyRow(plan), _creationTime: now - 21 * 86400000, orgId: org._id, businessId: savedBusiness._id, goalId: savedGoal._id, version: Number(savedPlan.version) + 1, runId: undefined, approvalId: undefined, weeklyReportedAt: undefined, status: "approved", expert: { ...expert, version: 7, plays: reviewPlays } }]);
  const reviewPlan = (await rows("strategies")).find(r => r.orgId === org._id && Number(r.version) === Number(savedPlan.version) + 1)!;
  await append("playResults", reviewPlays.flatMap((p, i) => [0, 1, 2].map(w => ({ orgId: org._id, strategyId: reviewPlan._id, playId: p.id, playName: p.name, weekStart: currentWeek - (3 - w) * 7 * 86400000, reach: i ? 0 : 100, steps: [i ? 0 : 10], spendUsd: 10, spendCurrency: "USD", ownerHours: 1, enteredBy: member.userId, updatedAt: now, stepNames: ["Paying customers"] }))));
  await page.reload();
  await page.getByRole("tab", { name: "Research", exact: true }).click();
  await page.getByRole("button", { name: "Open research and plan details", exact: true }).click();
  await page.locator("summary").filter({ hasText: "Other ideas, numbers and questions" }).click();
  const delivery = page.getByRole("article").filter({ has: page.getByRole("heading", { name: "Delivery review fixture", exact: true }) });
  const execution = page.getByRole("article").filter({ has: page.getByRole("heading", { name: "Execution review fixture", exact: true }) });
  await expect(delivery.getByText("Below scenario range", { exact: true })).toBeVisible();
  await expect(delivery.getByText(/^Next check:/)).toContainText("reach");
  await expect(delivery.getByText(/^Next check:/)).toContainText("Review complaints before continuing");
  await expect(delivery).not.toContainText("On track");
  await expect(delivery.getByText(/does not establish statistical confidence/)).toBeVisible();
  await expect(execution.getByText(/^Next check:/)).toContainText("Confirm whether the activity ran");
  await expect(execution).not.toContainText("hasn't run yet");
  await delivery.scrollIntoViewIfNeeded();
  await expectNoHorizontalScroll(page);
  await expectAccessible(page, "weekly scenario and next decision");
  await page.screenshot({ path: testInfo.outputPath("weekly-scenario-decision.png"), fullPage: false });
  expect(await actionSnapshot()).toEqual(before);
  expect(errors).toEqual([]);
});
