import { createHash } from "node:crypto";
import { expect, test } from "@playwright/test";
import { expectAccessible, expectNoHorizontalScroll, openDemo } from "./helpers";
import { localDemoFixtures } from "./local-demo-fixtures";
const envFile = process.env.CLIMBOS_DESIGN_E2E_ENV_FILE;
const { rows, append } = localDemoFixtures(envFile);

test("Owner records and corrects scoped customer progress without sending @mobile", async ({ page, baseURL }, testInfo) => {
  test.skip(!envFile, "Requires isolated loopback fixtures"); test.setTimeout(180000);
  expect(baseURL).toBe("http://127.0.0.1:3420");
  const slug = await openDemo(page);
  const org = (await rows("organizations")).find(row => row.slug === slug)!;
  expect(org.kind).toBe("demo");
  const hash = createHash("sha256").update("progress-fixture@example.com").digest("hex");
  await append("contacts", [{ orgId: org._id, emailHash: hash, emailDomain: "example.com", displayName: "Progress fixture", source: "demo_fixture", segments: ["customers"], createdAt: Date.now() }]);
  const effects = async () => Promise.all(["climbMessages", "workflowRuns", "approvals", "actionReceipts", "webhookDeliveries", "emailLog", "consentRecords"].map(async table => (await rows(table)).filter(row => row.orgId === org._id)));
  const before = await effects(); const errors: string[] = []; page.on("pageerror", e => errors.push(e.message));
  await page.goto(`/app/${slug}/connections`);
  await page.getByRole("button", { name: "Customer progress", exact: true }).click();
  const dialog = page.getByRole("dialog", { name: "Customer progress", exact: true });
  await dialog.getByLabel("Contact email", { exact: true }).fill("progress-fixture@example.com");
  await dialog.getByRole("button", { name: "Look up", exact: true }).click();
  await expect(dialog.getByText("No progress observations yet.", { exact: false })).toBeVisible();
  await dialog.getByLabel("Product or journey", { exact: true }).fill("Document app");
  await dialog.getByLabel("Reported progress", { exact: true }).click();
  await page.getByRole("option", { name: "Reached first value", exact: true }).click();
  await dialog.getByLabel("What this state means", { exact: true }).fill("Completed a real client export");
  await dialog.getByLabel("What you observed", { exact: true }).fill("Owner watched the customer complete an export");
  await dialog.getByLabel("Observation date", { exact: true }).fill("2026-11-16");
  await dialog.getByRole("button", { name: "Save observation", exact: true }).click();
  await expect(dialog.getByText("Document app: Reached first value", { exact: true })).toBeVisible();
  await dialog.getByRole("button", { name: "Update Document app", exact: true }).click();
  await dialog.getByLabel("Reported progress", { exact: true }).click();
  await page.getByRole("option", { name: "Unknown", exact: true }).click();
  await dialog.getByLabel("What you observed", { exact: true }).fill("The export was a demo; actual customer progress is unknown");
  await dialog.getByRole("button", { name: "Save observation", exact: true }).click();
  await expect(dialog.getByText("Document app: Unknown", { exact: true })).toBeVisible();
  await dialog.getByText("Observation history", { exact: true }).click();
  await expect(dialog.getByText("Revision 1 · Document app · Reached first value · as of 2026-11-16", { exact: true })).toBeVisible();
  await dialog.evaluate(async el => { await Promise.all(el.getAnimations({ subtree: true }).map(a => a.finished.catch(() => undefined))); });
  await expectAccessible(page, "Customer progress"); await expectNoHorizontalScroll(page);
  await page.screenshot({ path: testInfo.outputPath("customer-progress.png"), fullPage: false });
  await page.reload();
  await page.getByRole("button", { name: "Customer progress", exact: true }).click();
  await dialog.getByLabel("Contact email", { exact: true }).fill("progress-fixture@example.com");
  await dialog.getByRole("button", { name: "Look up", exact: true }).click();
  await expect(dialog.getByText("Document app: Unknown", { exact: true })).toBeVisible();
  expect((await rows("contactProgress")).filter(row => row.orgId === org._id)).toHaveLength(1);
  expect(await effects()).toEqual(before); expect(errors).toEqual([]);
});
