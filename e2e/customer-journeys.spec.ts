import { expect, test } from "@playwright/test";
import { expectAccessible, expectNoHorizontalScroll, openDemo } from "./helpers";
import { localDemoFixtures } from "./local-demo-fixtures";

const envFile = process.env.CLIMBOS_DESIGN_E2E_ENV_FILE;
const { cli, rows, append } = localDemoFixtures(envFile);

test("owner saves, starts, reviews and pauses a follow-up without authorizing a send @mobile", async ({ page, baseURL }, testInfo) => {
  test.skip(!envFile, "Requires isolated loopback fixtures"); test.setTimeout(180000);
  expect(baseURL).toBe("http://127.0.0.1:3420");
  const slug = await openDemo(page), org = (await rows("organizations")).find(row => row.slug === slug)!;
  expect(org.kind).toBe("demo");
  const member = (await rows("memberships")).find(row => row.orgId === org._id)!;
  const identity = JSON.stringify({ subject: `${member.userId}|journey-fixture`, tokenIdentifier: "test|journey-fixture" });
  await cli(["run", "marketing:importContacts", JSON.stringify({ slug, csv: "email,consent,consent_source,consent_date,segment\njourney@example.com,yes,signup,2026-10-01,follow-up-test" }), "--identity", identity]);
  const contact = (await rows("contacts")).find(row => row.orgId === org._id && (row.segments as string[]).includes("follow-up-test"))!;
  await cli(["run", "marketing:recordContactProgress", JSON.stringify({ slug, contactId: contact._id, expectedRevision: 0, scope: "Export onboarding", state: "started", criterion: "First useful export not yet observed", evidence: "Owner inspected the synthetic customer record", observedOn: new Date().toISOString().slice(0, 10) }), "--identity", identity]);
  const artifact = (await rows("artifacts")).find(row => row.orgId === org._id && row.kind === "email_sequence")!;
  await cli(["run", "content:decide", JSON.stringify({ slug, artifactId: artifact._id, decision: "approve" }), "--identity", identity]);
  if (!(await rows("connections")).some(row => row.orgId === org._id && row.provider === "email_resend")) await append("connections", [{ orgId: org._id, provider: "email_resend", status: "connected", isFixture: true, scopes: [], accountLabel: "Local fixture without credentials", createdBy: member.userId, createdAt: Date.now(), updatedAt: Date.now() }]);
  const effects = async () => Promise.all(["approvals", "actionReceipts", "emailLog", "consentRecords", "workflowRuns"].map(async table => (await rows(table)).filter(row => row.orgId === org._id)));
  const before = await effects(), errors: string[] = [];
  page.on("pageerror", error => errors.push(error.message));
  await page.goto(`/app/${slug}/customers`);
  await page.getByRole("tab", { name: "Follow-ups", exact: true }).click();
  await page.getByRole("button", { name: "New follow-up", exact: true }).click();
  const form = page.getByRole("form", { name: "New customer follow-up" });
  await form.getByLabel("Follow-up name", { exact: true }).fill("Useful export help");
  await form.getByLabel("Customer group", { exact: true }).click();
  await page.getByRole("option", { name: "follow-up-test", exact: true }).click();
  await form.getByLabel("Progress to follow", { exact: true }).click();
  await page.getByRole("option", { name: /Export onboarding · Started/ }).click();
  await form.getByLabel("Oldest acceptable observation (days)").fill("7");
  await form.getByLabel("Email for step 1", { exact: true }).click();
  await page.getByRole("option", { name: /First form in 7 days/ }).first().click();
  await expect(form.getByRole("button", { name: "Save follow-up", exact: true })).toBeDisabled();
  await form.getByLabel("Wait before step 1 (days)").fill("0");
  await form.getByRole("button", { name: "Add step", exact: true }).click();
  await form.getByLabel("Email for step 2", { exact: true }).click();
  await page.getByRole("option", { name: /First form in 7 days/ }).first().click();
  await form.getByLabel("Wait before step 2 (days)").fill("2");
  await form.getByRole("button", { name: "Save follow-up", exact: true }).click();
  const card = page.getByRole("article", { name: "Useful export help", exact: true });
  await expect(card.getByText("draft", { exact: true })).toBeVisible();
  expect((await rows("journeyContacts")).filter(row => row.orgId === org._id)).toHaveLength(0);
  await card.getByRole("button", { name: "Start tracking", exact: true }).click();
  await expect(card.getByText(/1 tracking · 0 waiting/)).toBeVisible();
  await expectAccessible(page, "Customer follow-up tracking"); await expectNoHorizontalScroll(page);
  await page.screenshot({ path: testInfo.outputPath("customer-followup.png"), fullPage: true });
  await card.getByRole("link", { name: "Review step 1", exact: true }).click();
  await expect(page.getByText("Follow-up: Useful export help", { exact: true })).toBeVisible();
  await expect(page.getByLabel("Who gets it", { exact: true })).toBeDisabled();
  await expect(page.getByLabel("Which email?", { exact: true })).toBeDisabled();
  await expect(page.getByLabel("Oldest acceptable observation (days)")).toBeDisabled();
  await expect(page.getByText("1 of 1 opted-in contacts qualify", { exact: true })).toBeVisible();
  await expectAccessible(page, "Saved follow-up send review"); await expectNoHorizontalScroll(page);
  const stepUrl = page.url();
  const saved = (await rows("customerJourneys")).find(row => row.orgId === org._id)!;
  // Another owner window can pause while this exact review remains open.
  await cli(["run", "customerJourneys:setStatus", JSON.stringify({ slug, journeyId: saved._id, revision: saved.revision, status: "paused" }), "--identity", identity]);
  await expect(page.getByText("Review this follow-up first", { exact: true })).toBeVisible();
  await expect(page.getByRole("button", { name: "Send", exact: true })).toHaveCount(0);
  await page.goto(`/app/${slug}/customers`); await page.getByRole("tab", { name: "Follow-ups", exact: true }).click();
  await card.getByRole("button", { name: "Resume tracking", exact: true }).click();
  await card.getByRole("button", { name: "Pause tracking", exact: true }).click();
  await expect(card.getByText("paused", { exact: true })).toBeVisible();
  await page.goto(stepUrl);
  await expect(page.getByText("Review this follow-up first", { exact: true })).toBeVisible();
  await expect(page.getByRole("button", { name: "Send", exact: true })).toHaveCount(0);
  expect(await effects()).toEqual(before); expect(errors).toEqual([]);
});
