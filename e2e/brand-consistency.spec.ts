import { expect, test } from "@playwright/test";
import { expectAccessible, expectNoHorizontalScroll, openDemo } from "./helpers";
import { localDemoFixtures } from "./local-demo-fixtures";

const envFile = process.env.CLIMBOS_DESIGN_E2E_ENV_FILE;
const { rows, append } = localDemoFixtures(envFile);

test("brand map reviews exact sources, retains exceptions and requires fresh review after brand changes @mobile", async ({ page, baseURL }, testInfo) => {
  test.skip(!envFile, "Requires an explicitly configured isolated local demo backend");
  test.setTimeout(180_000);
  expect(baseURL).toBe("http://127.0.0.1:3420");
  const errors: string[] = [];
  page.on("pageerror", error => errors.push(error.message));
  const slug = await openDemo(page);
  const org = (await rows("organizations")).find(row => row.slug === slug);
  if (!org || org.kind !== "demo") throw new Error("Only demo workspaces may receive these fixtures");
  const owner = (await rows("memberships")).find(row => row.orgId === org._id && row.role === "owner");
  if (!owner) throw new Error("The demo needs an owner");
  const now = Date.now();
  await append("landingPages", [0, 1].map(i => ({ orgId: org._id, slug: `brand-map-${slug}-${i}`, title: `Synthetic brand page ${i}`, brief: "Synthetic brand inspection", status: "live", version: 2, publishedVersion: 1, color: "#ffffff", content: JSON.stringify({ ctaLabel: "New draft text" }), publishedColor: i ? "#445566" : "#112233", publishedContent: JSON.stringify({ ctaLabel: "Ask us" }), views: 0, leads: 0, createdAt: now + i, updatedAt: now + i })));
  await append("designs", [{ orgId: org._id, title: "Synthetic saved poster", format: "custom", doc: JSON.stringify({ version: 1, pages: [{ background: { kind: "solid", color: "#445566" }, layers: [{ type: "text", fontFamily: "Inter", color: "#112233" }] }] }), pages: 1, createdBy: owner.userId, createdAt: now, updatedAt: now }]);
  const snapshot = async () => Promise.all(["landingPages", "designs", "workflowRuns", "approvals", "actionReceipts"].map(async table => (await rows(table)).filter(row => row.orgId === org._id).sort((a, b) => String(a._id).localeCompare(String(b._id)))));
  const before = await snapshot();
  await page.goto(`/app/${slug}/settings/brand`);
  await page.getByText("Brand consistency map", { exact: true }).click();
  const map = page.locator("#brand-consistency");
  await expect(map.getByText(/No currently confirmed brand rules/)).toBeVisible();
  const accents = map.getByRole("article").filter({ has: page.getByRole("heading", { name: "Hosted-page accent colors", exact: true }) });
  await accents.getByText(/Inspect \d+ saved sources/).click();
  await expect(accents.getByText("Published v1 · Published page snapshot").first()).toBeVisible();
  await expect(accents.getByRole("link", { name: "Synthetic brand page 0" })).toHaveAttribute("href", /\/pages\?id=/);
  const fonts = map.getByRole("article").filter({ has: page.getByRole("heading", { name: "Design text fonts", exact: true }) });
  await fonts.getByText(/Inspect \d+ saved sources/).click();
  await expect(fonts.getByText(/Saved design draft; not publishing approval/)).toBeVisible();
  await accents.getByText("Review this pattern", { exact: true }).click();
  await accents.getByRole("combobox", { name: "Your decision" }).click();
  await page.getByRole("option", { name: "This is an intentional exception", exact: true }).click();
  await expect(accents.getByRole("button", { name: "Save pattern review" })).toBeDisabled();
  const note = "Different accents suit these two offers. This exception is limited to their saved versions.";
  await accents.getByRole("textbox", { name: "Reason or correction" }).fill(note);
  await accents.getByRole("button", { name: "Save pattern review" }).click();
  await expect(accents.getByText("intentional exception", { exact: true })).toBeVisible();
  const decisions = async () => (await rows("brandPatternDecisions")).filter(row => row.orgId === org._id);
  const first = await decisions();
  expect(first).toHaveLength(1);
  expect(first[0]).toMatchObject({ state: "intentional_exception", note });
  // Saving the actual brand kit confirms a new rule snapshot and invalidates old exceptions.
  await page.getByRole("textbox", { name: "Voice", exact: true }).fill("Synthetic check: clear and helpful, with purposeful variation.");
  await page.getByRole("button", { name: "Save", exact: true }).click();
  await expect(map.getByText("Needs fresh review", { exact: true })).toBeVisible();
  await expect(map.getByText(/Voice: Synthetic check/)).toBeVisible();
  await accents.getByText("Recent review history (1, latest five)", { exact: true }).click();
  await expect(accents.getByText(/intentional exception · earlier snapshot/)).toBeVisible();
  expect((await decisions())[0].snapshot).toBe(first[0].snapshot);
  await accents.getByRole("combobox", { name: "Your decision" }).click();
  await page.getByRole("option", { name: "Reopen for review", exact: true }).click();
  await accents.getByRole("textbox", { name: "Reason or correction" }).fill("Recheck the accents against the new confirmed direction.");
  await accents.getByRole("button", { name: "Save pattern review" }).click();
  await expect(accents.getByText("reopened", { exact: true })).toBeVisible();
  expect(await decisions()).toHaveLength(2);
  expect((await rows("auditEvents")).filter(row => row.orgId === org._id && String(row.action).startsWith("brand.pattern_"))).toHaveLength(2);
  expect(await snapshot()).toEqual(before);
  await expectNoHorizontalScroll(page);
  await expectAccessible(page, "brand consistency map");
  await page.screenshot({ path: testInfo.outputPath("brand-consistency.png"), fullPage: true });
  expect(errors).toEqual([]);
});
