import { expect, test } from "@playwright/test";
import { expectAccessible, expectNoHorizontalScroll, openDemo } from "./helpers";
import { localDemoFixtures } from "./local-demo-fixtures";
const envFile = process.env.CLIMBOS_DESIGN_E2E_ENV_FILE;
const { rows, append } = localDemoFixtures(envFile);
const copyRow = ({ _id: _i, _creationTime: _c, ...data }: Record<string, unknown>) => data;

test("Results separates recorded sales from payment evidence @mobile", async ({ page, baseURL }, testInfo) => {
  test.skip(!envFile, "Requires isolated loopback fixtures");
  test.setTimeout(180_000);
  expect(baseURL).toBe("http://127.0.0.1:3420");
  const demoSlug = await openDemo(page);
  const original = (await rows("organizations")).find(row => row.slug === demoSlug);
  if (!original || original.kind !== "demo") throw new Error("Demo workspace required");
  const member = (await rows("memberships")).find(row => row.orgId === original._id);
  if (!member) throw new Error("Demo owner missing");
  const slug = `sale-evidence-${testInfo.project.name}-${Date.now()}`;
  await append("organizations", [{ ...copyRow(original), slug, name: "Sale evidence fixture", kind: "demo", timezone: "UTC", currency: "USD" }]);
  const org = (await rows("organizations")).find(row => row.slug === slug);
  if (!org || org.kind !== "demo") throw new Error("Isolated workspace missing");
  await append("memberships", [{ ...copyRow(member), orgId: org._id }]);
  const now = Date.now(); const occurredAt = now - 86_400_000;
  const event = { orgId: org._id, source: "crm", sourceEventId: "sale", customerRef: "customer", currency: "USD", amountMinor: 1000, refundedMinor: 0, kind: "order", occurredAt, ingestedAt: now, isFixture: false };
  // Old CRM mirrors were unmarked even in demos; their provenance must still exclude them.
  await append("revenueEvents", [event]);
  await append("metricDaily", [{ orgId: org._id, metricKey: "revenue", date: new Date(occurredAt).toISOString().slice(0, 10), value: 1000, source: "billing", kind: "observed", isFixture: false, ingestedAt: now, workspaceTimezone: "UTC", workspaceCurrency: "USD" }]);
  const effects = async () => Promise.all(["workflowRuns", "approvals", "actionReceipts", "forecastRuns", "webhookDeliveries"].map(async table => (await rows(table)).filter(row => row.orgId === org._id)));
  const before = await effects(); const errors: string[] = [];
  page.on("pageerror", error => errors.push(error.message));
  await page.goto(`/app/${slug}/results`);
  const payer = page.getByRole("article").filter({ has: page.getByRole("heading", { name: "First recorded paying customers", exact: true }) });
  await expect(payer.getByText("No data yet", { exact: true })).toBeVisible();
  await expect(payer.getByText(/customer count is unknown/)).toBeVisible();
  await expect(page.getByText(/older billing totals may include owner-recorded sales/).first()).toBeVisible();
  const cohorts = page.locator('section[aria-labelledby="cohorts-heading"]');
  await expect(cohorts.getByText(/Owner-recorded sales stay in the customer pipeline/)).toBeVisible();
  await expect(cohorts.getByRole("table")).toHaveCount(0);
  await page.getByRole("tab", { name: "Where it came from", exact: true }).click();
  const attribution = page.locator('section[aria-labelledby="attribution-heading"]');
  await expect(attribution.getByText("No billing events recorded in this period", { exact: true })).toBeVisible();
  await expect(attribution.getByText(/Owner-recorded sales stay in the customer pipeline/).first()).toBeVisible();
  await append("revenueEvents", [{ ...event, source: "fixture-billing", sourceEventId: "payment", isFixture: true }]);
  await expect(attribution.getByRole("table")).toBeVisible();
  await expect(attribution.getByText("$10.00", { exact: true }).first()).toBeVisible();
  await expect(attribution.getByText("$20.00", { exact: true })).toHaveCount(0);
  await expectAccessible(page, "separate sales and payments");
  await expectNoHorizontalScroll(page);
  await page.screenshot({ path: testInfo.outputPath("separate-sale-and-payment.png"), fullPage: true });
  expect(errors).toEqual([]);
  expect(await effects()).toEqual(before);
});
