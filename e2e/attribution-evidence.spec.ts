import { expect, test } from "@playwright/test";
import { expectAccessible, expectNoHorizontalScroll, openDemo } from "./helpers";
import { localDemoFixtures } from "./local-demo-fixtures";

const envFile = process.env.CLIMBOS_DESIGN_E2E_ENV_FILE;
const { rows, append } = localDemoFixtures(envFile);
const copyRow = ({ _id: _i, _creationTime: _c, ...data }: Record<string, unknown>) => data;

test("Results distinguishes payment events and unavailable attribution @mobile", async ({ page, baseURL }, testInfo) => {
  test.skip(!envFile, "Requires isolated loopback fixtures");
  test.setTimeout(180_000);
  expect(baseURL).toBe("http://127.0.0.1:3420");
  const demoSlug = await openDemo(page);
  const original = (await rows("organizations")).find(row => row.slug === demoSlug);
  if (!original || original.kind !== "demo") throw new Error("Demo workspace required");
  const member = (await rows("memberships")).find(row => row.orgId === original._id);
  if (!member) throw new Error("Demo owner missing");
  const slug = `attribution-${testInfo.project.name}-${Date.now()}`;
  await append("organizations", [{ ...copyRow(original), slug, name: "Attribution fixture", kind: "demo", timezone: "UTC", currency: "USD" }]);
  const org = (await rows("organizations")).find(row => row.slug === slug);
  if (!org || org.kind !== "demo") throw new Error("Isolated workspace missing");
  await append("memberships", [{ ...copyRow(member), orgId: org._id }]);
  const now = Date.now(); const day = 86_400_000;
  const order = { orgId: org._id, source: "fixture-billing", sourceEventId: "first", customerRef: "one-customer", currency: "USD", amountMinor: 1000, refundedMinor: 0, kind: "order", occurredAt: now - 2 * day, ingestedAt: now, isFixture: true };
  await append("revenueEvents", [order, { ...order, sourceEventId: "renewal", kind: "subscription_payment", occurredAt: now - day }]);
  await append("touches", [{ orgId: org._id, source: "fixture-billing", customerRef: "one-customer", channel: "unmatched paid ads", occurredAt: now - 3 * day, isFixture: true }]);
  await append("platformClaims", [{ orgId: org._id, platform: "google_ads", date: new Date(now - day).toISOString().slice(0, 10), conversions: 1, conversionValueMinor: 1000, spendMinor: 100, currency: "USD", isFixture: true, spendOrigin: "owner_reported" }]);
  const effects = async () => Promise.all(["workflowRuns", "approvals", "actionReceipts"].map(async table => (await rows(table)).filter(row => row.orgId === org._id)));
  const before = await effects(); const errors: string[] = [];
  page.on("pageerror", error => errors.push(error.message));
  await page.goto(`/app/${slug}/results`);
  await page.getByRole("tab", { name: "Where it came from", exact: true }).click();
  const section = page.locator('section[aria-labelledby="attribution-heading"]');
  await expect(section.getByRole("columnheader", { name: "Payment events", exact: true })).toBeVisible();
  await expect(section.getByText(/not unique customers/).first()).toBeVisible();
  await expect(section.getByText("Rows reconcile", { exact: true })).toBeVisible();
  await expect(section.getByText("Unmatched paid ads", { exact: true })).toBeVisible();
  const claims = page.locator('section[aria-labelledby="claims-heading"]');
  await expect(claims.getByText("Owner-reported import", { exact: true })).toBeVisible();
  await expect(claims.getByText("Unknown", { exact: true })).toBeVisible();
  await expect(claims.getByText(/Channel-name guesses/)).toBeVisible();
  await expect(claims.getByText("20.00×", { exact: true })).toHaveCount(0);
  await expectAccessible(page, "attribution definitions");
  await expectNoHorizontalScroll(page);
  await page.screenshot({ path: testInfo.outputPath("attribution-definitions.png"), fullPage: true });
  await append("revenueEvents", [{ ...order, amountMinor: 9000 }]);
  await expect(section.getByText("Channel credit unavailable", { exact: true })).toBeVisible();
  await expect(section.getByText(/conflicting values/)).toBeVisible();
  await expect(section.getByText("Rows reconcile", { exact: true })).toHaveCount(0);
  await expectAccessible(page, "unavailable attribution");
  await expectNoHorizontalScroll(page);
  await page.screenshot({ path: testInfo.outputPath("attribution-conflict.png"), fullPage: true });
  expect(errors).toEqual([]);
  expect(await effects()).toEqual(before);
});
