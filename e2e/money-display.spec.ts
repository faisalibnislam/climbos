import { expect, test } from "@playwright/test";
import { expectAccessible, expectNoHorizontalScroll, openDemo } from "./helpers";
import { localDemoFixtures } from "./local-demo-fixtures";
const envFile = process.env.CLIMBOS_DESIGN_E2E_ENV_FILE;
const { rows, append } = localDemoFixtures(envFile);
const copyRow = ({ _id: _i, _creationTime: _c, ...data }: Record<string, unknown>) => data;

test("Results preserves yen, three-decimal currency and cents in larger totals @mobile", async ({ page, baseURL }, testInfo) => {
  test.skip(!envFile, "Requires isolated loopback fixtures");
  test.setTimeout(180_000);
  expect(baseURL).toBe("http://127.0.0.1:3420");
  const demoSlug = await openDemo(page);
  const original = (await rows("organizations")).find(row => row.slug === demoSlug);
  if (!original || original.kind !== "demo") throw new Error("Demo workspace required");
  const member = (await rows("memberships")).find(row => row.orgId === original._id);
  if (!member) throw new Error("Demo owner missing");
  const slug = `money-${testInfo.project.name}-${Date.now()}`;
  await append("organizations", [{ ...copyRow(original), slug, name: "Currency display fixture", kind: "demo", timezone: "UTC", currency: "KWD" }]);
  const org = (await rows("organizations")).find(row => row.slug === slug);
  if (!org || org.kind !== "demo") throw new Error("Isolated workspace missing");
  await append("memberships", [{ ...copyRow(member), orgId: org._id }]);
  const now = Date.now(); const occurredAt = now - 86_400_000;
  const event = { orgId: org._id, source: "fixture-billing", customerRef: "customer", refundedMinor: 0, kind: "order", occurredAt, ingestedAt: now, isFixture: true };
  await append("revenueEvents", [{ ...event, sourceEventId: "yen", currency: "JPY", amountMinor: 1200 }, { ...event, sourceEventId: "dinar", currency: "KWD", amountMinor: 12345 }, { ...event, sourceEventId: "dollar", currency: "USD", amountMinor: 100001 }]);
  await append("metricDaily", [{ orgId: org._id, metricKey: "revenue", date: new Date(occurredAt).toISOString().slice(0, 10), value: 12345, source: "billing", kind: "observed", isFixture: true, ingestedAt: now, workspaceTimezone: "UTC", workspaceCurrency: "KWD" }]);
  const state = async () => Promise.all(["revenueEvents", "metricDaily", "campaigns", "approvals", "actionReceipts", "forecastRuns", "webhookDeliveries"].map(async table => (await rows(table)).filter(row => row.orgId === org._id)));
  const before = await state(); const errors: string[] = [];
  page.on("pageerror", error => errors.push(error.message));
  await page.goto(`/app/${slug}/results`);
  const revenue = page.getByRole("article").filter({ has: page.getByRole("heading", { name: "Revenue (net of refunds)", exact: true }) });
  await expect(revenue.getByText(/KWD\s+12\.345/, { exact: true })).toBeVisible();
  await expect(revenue.getByText(/Recorded subtotal from 1 of 30 days/)).toBeVisible();
  await page.getByRole("tab", { name: "Where it came from", exact: true }).click();
  const yen = page.getByRole("table", { name: /attribution, JPY/ });
  const dinar = page.getByRole("table", { name: /attribution, KWD/ });
  const dollar = page.getByRole("table", { name: /attribution, USD/ });
  await expect(yen.getByText("¥1,200", { exact: true }).first()).toBeVisible();
  await expect(dinar.getByText(/KWD\s+12\.345/, { exact: true }).first()).toBeVisible();
  await expect(dollar.getByText("$1,000.01", { exact: true }).first()).toBeVisible();
  await expectAccessible(page, "currency-specific values");
  await expectNoHorizontalScroll(page);
  await page.screenshot({ path: testInfo.outputPath("exact-currency-values.png"), fullPage: true });
  expect(errors).toEqual([]);
  expect(await state()).toEqual(before);
});
