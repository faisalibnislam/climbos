import { expect, test } from "@playwright/test";
import { expectAccessible, expectNoHorizontalScroll, openDemo } from "./helpers";
import { localDemoFixtures } from "./local-demo-fixtures";
const envFile = process.env.CLIMBOS_DESIGN_E2E_ENV_FILE;
const { rows, append } = localDemoFixtures(envFile);
const copyRow = ({ _id: _i, _creationTime: _c, ...data }: Record<string, unknown>) => data;

test("Results does not call a refunded customer's renewal a new payer @mobile", async ({ page, baseURL }, testInfo) => {
  test.skip(!envFile, "Requires isolated loopback fixtures");
  test.setTimeout(180_000);
  expect(baseURL).toBe("http://127.0.0.1:3420");
  const demoSlug = await openDemo(page);
  const original = (await rows("organizations")).find(row => row.slug === demoSlug);
  if (!original || original.kind !== "demo") throw new Error("Demo workspace required");
  const member = (await rows("memberships")).find(row => row.orgId === original._id);
  if (!member) throw new Error("Demo owner missing");
  const slug = `payer-${testInfo.project.name}-${Date.now()}`;
  await append("organizations", [{ ...copyRow(original), slug, name: "First payer fixture", kind: "demo", timezone: "UTC", currency: "USD" }]);
  const org = (await rows("organizations")).find(row => row.slug === slug);
  if (!org || org.kind !== "demo") throw new Error("Isolated workspace missing");
  await append("memberships", [{ ...copyRow(member), orgId: org._id }]);
  const now = Date.now(); const day = 86_400_000;
  const payment = { orgId: org._id, source: "fixture-billing", sourceEventId: "first", customerRef: "customer", currency: "USD", amountMinor: 1000, refundedMinor: 1000, kind: "order", occurredAt: now - 100 * day, ingestedAt: now, isFixture: true };
  await append("revenueEvents", [payment, { ...payment, sourceEventId: "renewal", refundedMinor: 0, kind: "subscription_payment", occurredAt: now - day }]);
  const effects = async () => Promise.all(["workflowRuns", "approvals", "actionReceipts", "forecastRuns"].map(async table => (await rows(table)).filter(row => row.orgId === org._id)));
  const before = await effects(); const errors: string[] = [];
  page.on("pageerror", error => errors.push(error.message));
  await page.goto(`/app/${slug}/results`);
  const counts = page.locator('section[aria-labelledby="funnel-heading"]');
  const payer = counts.getByRole("listitem").filter({ hasText: "First recorded paying customers" });
  await expect(payer).toBeVisible();
  await expect(payer.getByText("0", { exact: true })).toBeVisible();
  await expect(payer.getByText(/Completeness of billing history is unknown/)).toBeVisible();
  await expectAccessible(page, "first payer definition");
  await expectNoHorizontalScroll(page);
  await page.screenshot({ path: testInfo.outputPath("recorded-repeat-customer.png"), fullPage: true });
  await append("revenueEvents", [{ ...payment, sourceEventId: "invalid-earlier", amountMinor: 1.5, refundedMinor: 0, occurredAt: now - 110 * day }]);
  await expect(payer.getByText(/earlier customer history contains invalid/)).toBeVisible();
  await expect(payer.getByText("0", { exact: true })).toHaveCount(0);
  await expectAccessible(page, "unknown first payer history");
  await expectNoHorizontalScroll(page);
  expect(errors).toEqual([]);
  expect(await effects()).toEqual(before);
  await page.screenshot({ path: testInfo.outputPath("unknown-customer-history.png"), fullPage: true });
});
