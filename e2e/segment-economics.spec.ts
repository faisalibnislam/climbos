import { expect, test } from "@playwright/test";
import { expectAccessible, expectNoHorizontalScroll, openDemo } from "./helpers";
import { localDemoFixtures } from "./local-demo-fixtures";
import { focusedPlanFixture } from "../tests/fixtures/focusedPlan";

const envFile = process.env.CLIMBOS_DESIGN_E2E_ENV_FILE;
const { rows, append } = localDemoFixtures(envFile);
const copyRow = (row: Record<string, unknown>) => Object.fromEntries(Object.entries(row).filter(([key]) => key !== "_id" && key !== "_creationTime"));

test("focused plans preserve unknown segment costs and explicit currency precision @mobile", async ({ page, baseURL }, testInfo) => {
  test.skip(!envFile, "Requires isolated loopback fixtures"); test.setTimeout(90_000); page.setDefaultTimeout(15_000);
  expect(baseURL).toBe("http://127.0.0.1:3420");
  const demoSlug = await openDemo(page);
  const original = (await rows("organizations")).find(row => row.slug === demoSlug);
  if (!original || original.kind !== "demo") throw new Error("Isolated demo required");
  const member = (await rows("memberships")).find(row => row.orgId === original._id);
  const business = (await rows("businesses")).find(row => row.orgId === original._id);
  const goal = (await rows("goals")).find(row => row.orgId === original._id && row.status === "active");
  const plan = (await rows("strategies")).find(row => row.orgId === original._id);
  if (!member || !business || !goal || !plan) throw new Error("Demo records required");
  const slug = `segments-${testInfo.project.name}-${Date.now()}`;
  await append("organizations", [{ ...copyRow(original), slug, name: "Synthetic customer economics" }]);
  const org = (await rows("organizations")).find(row => row.slug === slug)!;
  await append("memberships", [{ ...copyRow(member), orgId: org._id }]);
  await append("businesses", [{ ...copyRow(business), orgId: org._id, unitEconomics: { updatedAt: Date.now() } }]);
  const savedBusiness = (await rows("businesses")).find(row => row.orgId === org._id)!;
  await append("goals", [{ ...copyRow(goal), orgId: org._id }]);
  const savedGoal = (await rows("goals")).find(row => row.orgId === org._id)!;
  const focused = focusedPlanFixture();
  await append("strategies", [{ ...copyRow(plan), orgId: org._id, businessId: savedBusiness._id, goalId: savedGoal._id, runId: undefined, approvalId: undefined, expert: { ...(plan.expert as Record<string, unknown>), focusedMove: focused.focusedMove, strategicDirection: focused.strategicDirection, strategyExploration: focused.strategyExploration, preparedWork: focused.preparedWork, timing: focused.timing, phases: focused.phases, weekOneChecklist: focused.weekOneChecklist, plays: [] } }]);
  const effects = async () => Promise.all(["artifacts", "approvals", "actionReceipts", "workflowRuns"].map(async table => (await rows(table)).filter(row => row.orgId === org._id)));
  const before = await effects();
  const open = async () => {
    await page.goto(`/app/${slug}/plan`);
    await page.getByRole("tab", { name: "Research", exact: true }).click();
    await page.getByRole("button", { name: "Open research and plan details", exact: true }).click();
    await page.locator("summary").filter({ hasText: "Other ideas, numbers and questions" }).click();
  };
  await open();
  const card = page.getByRole("heading", { name: "Compare customer groups" }).locator("../..");
  await card.getByRole("button", { name: "Add group", exact: true }).click();
  await card.getByLabel("Customer group", { exact: true }).fill("Service customers");
  await card.getByLabel("Currency (ISO code)").fill("KWD");
  await card.getByLabel("Period (days)").fill("90");
  await card.getByLabel("Customers in group").fill("10");
  await card.getByLabel("Costs included", { exact: true }).fill("Service hours and payment fees");
  await expect(card).toContainText("Contribution unknown");
  await expect(card).toContainText("Cost coverage unknown");
  await card.getByRole("button", { name: "Save groups" }).click();
  const economics = async () => (await rows("businesses")).find(row => row._id === savedBusiness._id)!.unitEconomics as { segmentEconomics: Record<string, unknown>[] };
  await expect.poll(economics).toMatchObject({ segmentEconomics: [{ segment: "Service customers", costCoverage: "unknown" }] });
  expect((await economics()).segmentEconomics[0]).not.toHaveProperty("netRevenue");
  expect((await economics()).segmentEconomics[0]).not.toHaveProperty("variableCosts");
  await open();
  await expect(card.getByLabel("Variable costs (KWD)")).toHaveValue("");
  await card.getByLabel("Net revenue (KWD)").fill("10.123");
  await card.getByLabel("Variable costs (KWD)").fill("3.001");
  await expect(card).toContainText("7.122");
  await expect(card).toContainText("Cost coverage unknown");
  await card.getByRole("combobox", { name: "Cost coverage", exact: true }).selectOption("complete");
  await card.getByRole("button", { name: "Save groups" }).click();
  await expect.poll(economics).toMatchObject({ segmentEconomics: [{ netRevenue: 10.123, variableCosts: 3.001, costCoverage: "complete" }] });
  await expect(card).toContainText("You report complete costs for this boundary");
  await card.getByLabel("Unknown costs (comma-separated)").fill("Support time");
  await expect(card).toContainText("Complete cost coverage requires");
  await card.getByRole("button", { name: "Save groups" }).click();
  expect((await economics()).segmentEconomics[0]).toMatchObject({ costCoverage: "complete", unknownCosts: [] });
  await card.getByRole("combobox", { name: "Cost coverage", exact: true }).selectOption("incomplete");
  await card.getByRole("button", { name: "Save groups" }).click();
  await expect.poll(economics).toMatchObject({ segmentEconomics: [{ costCoverage: "incomplete", unknownCosts: ["Support time"] }] });
  await expect(card).toContainText("Costs incomplete: Support time");
  await expectNoHorizontalScroll(page); await expectAccessible(page, "Customer group economics");
  await card.screenshot({ path: testInfo.outputPath("segment-economics.png") });
  expect(await effects()).toEqual(before);
});
