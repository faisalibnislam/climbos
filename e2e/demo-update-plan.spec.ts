import { expect, test } from "@playwright/test";
import { expectAccessible, expectNoHorizontalScroll, openDemo } from "./helpers";
import { localDemoFixtures } from "./local-demo-fixtures";

const envFile = process.env.CLIMBOS_DESIGN_E2E_ENV_FILE;
const { rows } = localDemoFixtures(envFile);

test("demo update prepares the current plan without provider or publishing actions @mobile", async ({ page, baseURL }, testInfo) => {
  test.skip(!envFile, "Requires the explicitly isolated local fixture backend");
  test.setTimeout(150_000);
  page.setDefaultTimeout(15_000);
  expect(baseURL).toBe("http://127.0.0.1:3420");
  const slug = await openDemo(page);
  const org = (await rows("organizations")).find(row => row.slug === slug)!;
  expect(org.kind).toBe("demo");
  const original = (await rows("strategies")).find(row => row.orgId === org._id)!;
  const authority = async () => Promise.all(["artifacts", "actionReceipts"].map(async table => (await rows(table)).filter(row => row.orgId === org._id)));
  const before = await authority();
  await page.goto(`/app/${slug}/plan`);
  const views = page.getByRole("tablist", { name: "Plan views", exact: true });
  await views.getByRole("tab", { name: "Prepared work", exact: true }).click();
  await page.getByRole("button", { name: "Update my plan", exact: true }).first().click();
  await page.getByRole("alertdialog").getByRole("button", { name: "Update my plan", exact: true }).click();
  await page.getByRole("button", { name: "See the update", exact: true }).click();
  await views.getByRole("tab", { name: "Next steps", exact: true }).click();
  const learning = page.getByRole("region", { name: "Check your progress", exact: true });
  await expect(learning.getByRole("button", { name: "Record outcome", exact: true })).toBeVisible();
  await expect(learning).toContainText("Previously unresolved scoping decisions identified");
  await views.getByRole("tab", { name: "Strategy options", exact: true }).click();
  for (const name of ["Review one past handoff", "Borrow a film production call sheet", "Become known for the brief you decline"]) await expect(page.getByRole("heading", { name, exact: true })).toBeVisible();
  await views.getByRole("tab", { name: "Prepared work", exact: true }).click();
  await page.getByText("Private intake review brief", { exact: false }).filter({ hasText: "Private draft" }).click();
  await expect(page.getByRole("textbox", { name: "Edit Private intake review brief", exact: true })).toHaveValue(/Demo draft — not customer research or a completed test/);
  await expect(page.getByRole("region", { name: "Your prepared drafts", exact: true })).toContainText("Nothing has been shared");
  await expectNoHorizontalScroll(page);
  await expectAccessible(page, "Generated demo plan");
  await page.screenshot({ path: testInfo.outputPath("updated-demo-plan.png") });
  const plans = (await rows("strategies")).filter(row => row.orgId === org._id);
  const updated = plans.find(row => row._id !== original._id)!;
  expect(plans.find(row => row._id === original._id)?.status).toBe("approved");
  expect(updated.status).toBe("needs_approval");
  const run = (await rows("workflowRuns")).find(row => row._id === updated.runId)!;
  expect(run.status).toBe("verified");
  expect(run.isFixture).toBe(true);
  const usage = (await rows("usageEvents")).filter(row => row.runId === run._id);
  expect(usage.length).toBeGreaterThan(0);
  expect(usage.every(row => row.costMicros === 0 && row.provider === "fixture")).toBe(true);
  expect(await authority()).toEqual(before);
  expect((await rows("approvals")).filter(row => row.subjectId === updated._id)).toMatchObject([{ status: "pending", actionKind: "approve_plan" }]);
});
