import { expect, test } from "@playwright/test";
import { expectAccessible, expectNoHorizontalScroll, openDemo } from "./helpers";
import { localDemoFixtures } from "./local-demo-fixtures";
import { focusedPlanFixture } from "../tests/fixtures/focusedPlan";
import { futureCampaignTimingFixture } from "../tests/fixtures/campaignTiming";
import { offerAssessmentFixture } from "../tests/fixtures/offerAssessment";
import { diagnose } from "../shared/agents/diagnosis";

const envFile = process.env.CLIMBOS_DESIGN_E2E_ENV_FILE;
const { rows, append } = localDemoFixtures(envFile);
const copyRow = (row: Record<string, unknown>) => Object.fromEntries(Object.entries(row).filter(([key]) => key !== "_id" && key !== "_creationTime"));

test("focused plan exposes all three options and selecting bold grants no action authority @mobile", async ({ page, baseURL }, testInfo) => {
  test.skip(!envFile, "Requires explicitly configured isolated loopback fixtures");
  test.setTimeout(150_000);
  page.setDefaultTimeout(15_000);
  expect(baseURL).toBe("http://127.0.0.1:3420");
  const demoSlug = await openDemo(page);
  const original = (await rows("organizations")).find(row => row.slug === demoSlug);
  if (!original || original.kind !== "demo") throw new Error("Isolated demo required");
  const member = (await rows("memberships")).find(row => row.orgId === original._id);
  const business = (await rows("businesses")).find(row => row.orgId === original._id);
  const goal = (await rows("goals")).find(row => row.orgId === original._id && row.status === "active");
  const plan = (await rows("strategies")).find(row => row.orgId === original._id);
  if (!member || !business || !goal || !plan) throw new Error("Demo records required");
  const slug = `focused-options-${testInfo.project.name}-${Date.now()}`;
  await append("organizations", [{ ...copyRow(original), slug, name: "Synthetic strategy options" }]);
  const org = (await rows("organizations")).find(row => row.slug === slug)!;
  await append("memberships", [{ ...copyRow(member), orgId: org._id }]);
  await append("businesses", [{ ...copyRow(business), orgId: org._id }]);
  const savedBusiness = (await rows("businesses")).find(row => row.orgId === org._id)!;
  await append("goals", [{ ...copyRow(goal), orgId: org._id }]);
  const savedGoal = (await rows("goals")).find(row => row.orgId === org._id)!;
  const fixture = focusedPlanFixture();
  fixture.focusedMove.offerAssessment = offerAssessmentFixture();
  fixture.focusedMove.timingAssessment = futureCampaignTimingFixture();
  await append("strategies", [{ ...copyRow(plan), orgId: org._id, businessId: savedBusiness._id, goalId: savedGoal._id, runId: undefined, approvalId: undefined, summary: fixture.summary, expert: { ...(plan.expert as Record<string, unknown>), constraintDiagnosis: diagnose({ funnel: { periodDays: 90, leads: 100, activated: 12, newCustomers: 3, activationKind: "value" }, salesCycleDays: 45, salesCycleEstimate: { category: "A few weeks to two months", source: "owner" } }), focusedMove: { ...fixture.focusedMove, timingAssessment: { ...fixture.focusedMove.timingAssessment, researchRetrievedAt: new Date().toISOString() } }, strategicDirection: fixture.strategicDirection, strategyExploration: fixture.strategyExploration, preparedWork: fixture.preparedWork, timing: fixture.timing, phases: fixture.phases, weekOneChecklist: fixture.weekOneChecklist, plays: [] } }]);
  const savedPlan = (await rows("strategies")).find(row => row.orgId === org._id)!;
  await append("experiments", [{ ...fixture.experiments[0], orgId: org._id, strategyId: savedPlan._id, status: "proposed", createdAt: Date.now() }]);
  const snapshot = async () => Promise.all(["artifacts", "approvals", "actionReceipts", "workflowRuns", "climbMessages"].map(async table => (await rows(table)).filter(row => row.orgId === org._id)));
  const before = await snapshot();
  await page.goto(`/app/${slug}/plan`);
  const planViews = page.getByRole("tablist", { name: "Plan views", exact: true });
  await expect(planViews.getByRole("tab", { name: "Next steps", exact: true })).toHaveAttribute("aria-selected", "true");
  const primaryLearning = page.getByRole("region", { name: "Check your progress", exact: true });
  await expect(primaryLearning.getByRole("button", { name: "Record outcome", exact: true })).toBeVisible();
  await expect(primaryLearning).toContainText(fixture.experiments[0].primaryMetric);
  await page.getByRole("tab", { name: "Why this plan", exact: true }).click();
  const campaignTiming = page.getByRole("region", { name: "Campaign timing recommendation" });
  await expect(campaignTiming).toContainText("Synthetic local booking event");
  await expect(campaignTiming).toContainText("Suggestion only. Nothing is scheduled.");
  await campaignTiming.getByText("Timing details and sources", { exact: true }).click();
  await expect(campaignTiming).toContainText("America/New_York");
  await expect(campaignTiming).toContainText("Preparation: 14 days");
  await expect(campaignTiming).toContainText("Delivery or service: 2 days");
  await expect(campaignTiming).toContainText(`Checked ${new Date().toISOString().slice(0, 10)}`);
  await expect(campaignTiming.getByRole("link", { name: "Open source", exact: true })).toHaveAttribute("href", fixture.focusedMove.timingAssessment.moment.evidence[0].sourceUrl!);
  await expectNoHorizontalScroll(page);
  await expectAccessible(page, "Focused campaign timing");
  await campaignTiming.screenshot({ path: testInfo.outputPath("campaign-timing.png") });
  const offer = page.getByRole("region", { name: "Offer recommendation and test" });
  await expect(offer).toContainText("Advice only · changes need your approval");
  await expect(offer).toContainText("Reported by your team");
  await expect(offer).toContainText("Current $50 from $100 · proposed $40 from $95");
  await expect(offer).toContainText("About 1.25 sales at the new price equal one current sale.");
  await offer.getByText("See test plan, options, and risks", { exact: true }).click();
  await expect(offer).toContainText("Incremental completed first-time jobs");
  await expect(offer).toContainText("21 days");
  await expect(offer).toContainText("Sales may come earlier, not grow");
  await expect(offer).toContainText("reported by your team");
  await expectNoHorizontalScroll(page);
  await expectAccessible(page, "Focused offer economics");
  await offer.screenshot({ path: testInfo.outputPath("offer-economics.png") });
  await page.getByRole("tab", { name: "Strategy options", exact: true }).click();
  const section = page.getByRole("region", { name: "Grounded, adjacent and bold strategy options" });
  for (const mode of ["grounded", "adjacent", "bold"] as const) await expect(section.getByRole("heading", { name: fixture.strategyExploration[mode].title })).toBeVisible();
  await expect(section).toContainText("not an execution ranking");
  await expect(section).toContainText("it does not start work");
  const bold = section.locator("article").filter({ has: page.getByRole("heading", { name: fixture.strategyExploration.bold.title }) });
  await bold.getByText("Explore the idea and its test", { exact: true }).click();
  await expect(bold).toContainText("No matching precedent used");
  await expect(bold).toContainText("Continue if:");
  await expect(bold).toContainText("Change if:");
  await expect(bold).toContainText("Stop if:");
  await bold.getByRole("combobox", { name: "Your decision", exact: true }).click();
  await page.getByRole("option", { name: "Select this option", exact: true }).click();
  await bold.getByRole("button", { name: "Save feedback", exact: true }).click();
  await expect(bold).toContainText("Last owner record: selected; test not started");
  expect((await rows("strategyExplorationFeedback")).filter(row => row.orgId === org._id)).toMatchObject([{ mode: "bold", decision: "selected", testState: "not_started" }]);
  const learning = page.locator("details").filter({ has: page.locator("summary", { hasText: "What new plans learn from your feedback" }) });
  await learning.locator("summary").click();
  await expect(learning).toContainText("1 included");
  await expect(learning).toContainText("Included for the next plan");
  await learning.getByRole("button", { name: "Stop using", exact: true }).click();
  await expect(learning).toContainText("0 included");
  await expect(learning).toContainText("Retired");
  await learning.getByRole("button", { name: "Use again", exact: true }).click();
  await expect(learning).toContainText("1 included");
  await bold.getByRole("combobox", { name: "Your decision", exact: true }).click();
  await page.getByRole("option", { name: "Reject this option", exact: true }).click();
  await bold.getByRole("button", { name: "Save feedback", exact: true }).click();
  await expect(learning).toContainText("Replaced by a newer report");
  await expect(learning).toContainText("1 included");
  await expect(learning.getByRole("button", { name: "Stop using", exact: true })).toHaveCount(1);
  await expectNoHorizontalScroll(page);
  // Check the stable review view after the save notifications finish animating and dismiss.
  await expect(page.getByRole("status").filter({ hasText: "Saved for this workspace" })).toHaveCount(0, { timeout: 10_000 });
  await expectAccessible(page, "Focused strategy options");
  await bold.screenshot({ path: testInfo.outputPath("bold-option.png") });
  const feedbackBeforeDiscussion = (await rows("strategyExplorationFeedback")).filter(row => row.orgId === org._id);
  await bold.getByRole("button", { name: "Discuss this option", exact: true }).click();
  const optionDiscussion = page.getByRole("textbox", { name: "Message Climb AI", exact: true });
  await expect(optionDiscussion).toHaveValue(/Explore the bold option/);
  await expect(optionDiscussion).toHaveValue(new RegExp(fixture.strategyExploration.bold.title));
  await optionDiscussion.fill("");
  await page.getByRole("button", { name: "Close Climb AI", exact: true }).click();
  expect((await rows("strategyExplorationFeedback")).filter(row => row.orgId === org._id)).toEqual(feedbackBeforeDiscussion);
  expect(await snapshot()).toEqual(before);
  await page.getByRole("tab", { name: "Research", exact: true }).click();
  await page.getByRole("button", { name: "Open research and plan details", exact: true }).click();
  await page.getByText("Where you stand and what the numbers mean", { exact: true }).click();
  await page.getByText("What your reported numbers show", { exact: true }).click();
  const diagnosis = page.locator("summary", { hasText: /^What your reported numbers show$/ }).locator("..");
  await expect(diagnosis).toContainText("45-day planning assumption from the owner-selected category");
  await expect(diagnosis).toContainText("actual time to buy has not been verified");
  await expect(diagnosis).toContainText("not independently verified measurements or proof of cause");
  await expect(diagnosis).toContainText("People sign up but don't get going");
  await expect(diagnosis).toContainText("12 of 100");
  await expect(diagnosis).toContainText("Alternative explanation");
  await expectNoHorizontalScroll(page);
  await expectAccessible(page, "Focused diagnosis evidence");
  await diagnosis.screenshot({ path: testInfo.outputPath("diagnosis-evidence.png") });
  await planViews.getByRole("tab", { name: "Next steps", exact: true }).click();
  const experiments = primaryLearning;
  await expect(experiments).toContainText(fixture.focusedMove.title);
  await expect(experiments).toContainText("1 day");
  await expect(experiments).toContainText("An observation alone does not prove cause");
  await experiments.getByText("Who, comparison, and when to stop", { exact: true }).click();
  await expect(experiments).toContainText(fixture.experiments[0].population);
  await expect(experiments).toContainText(fixture.experiments[0].baselineBasis);
  await experiments.getByRole("button", { name: "Record outcome", exact: true }).click();
  await experiments.getByRole("button", { name: "Didn't run", exact: true }).click();
  await experiments.getByRole("button", { name: "Save", exact: true }).click();
  const outcomeNotice = page.getByRole("status").filter({ hasText: "Outcome saved" });
  await expect(outcomeNotice).toBeVisible();
  await expect(experiments.getByText("Not run", { exact: true })).toBeVisible();
  await expect(outcomeNotice).toHaveCount(0, { timeout: 10_000 });
  await expectNoHorizontalScroll(page);
  await expectAccessible(page, "Primary observational test outcome");
  await experiments.screenshot({ path: testInfo.outputPath("primary-learning-test.png") });
  const recorded = (await rows("experiments")).find(row => row.orgId === org._id)!;
  expect(recorded).toMatchObject({ status: "stopped", analyses: [{ executed: false, inference: "not_run" }] });
  await experiments.getByRole("button", { name: "Update outcome", exact: true }).click();
  await experiments.getByRole("button", { name: "Ran", exact: true }).click();
  await experiments.getByLabel("Unit or amount meaning", { exact: true }).fill("scoping decisions");
  await experiments.getByLabel("Recorded value(optional)", { exact: true }).fill("3");
  await experiments.getByLabel("Comparison value(optional)", { exact: true }).fill("1");
  await experiments.getByLabel("What the value covers", { exact: true }).fill("Unresolved decisions in one synthetic past brief");
  await experiments.getByLabel("What the comparison covers(optional)", { exact: true }).fill("The same brief before the proposed questions");
  await experiments.getByRole("button", { name: "Save", exact: true }).click();
  await expect(experiments).toContainText("Recorded value: 3 scoping decisions");
  const savedNotice = page.getByRole("status").filter({ hasText: /Saved as analysis|Outcome saved/ });
  await expect(savedNotice).toBeVisible();
  await expect(savedNotice).toHaveCount(0, { timeout: 10_000 });
  await experiments.getByRole("button", { name: "Update outcome", exact: true }).click();
  await experiments.getByLabel("Recorded value(optional)", { exact: true }).fill("0");
  await experiments.getByRole("button", { name: "Save", exact: true }).click();
  await expect(savedNotice).toBeVisible();
  await expect(savedNotice).toHaveCount(0, { timeout: 10_000 });
  await expect(experiments).toContainText("Recorded value: 0 scoping decisions");
  await expect(experiments).toContainText("Comparison value: 1 scoping decisions");
  await expect(experiments).toContainText("not proof of cause");
  await expectNoHorizontalScroll(page);
  await expectAccessible(page, "Primary metric measurement");
  await experiments.screenshot({ path: testInfo.outputPath("primary-metric-measurement.png") });
  const measured = (await rows("experiments")).find(row => row.orgId === org._id)!;
  expect((measured.analyses as { measurement?: unknown }[]).at(-1)?.measurement).toMatchObject({ type: "count", value: 0, comparisonValue: 1, unit: "scoping decisions" });
  await experiments.getByRole("button", { name: "Update outcome", exact: true }).click();
  await experiments.getByRole("combobox", { name: "Measurement", exact: true }).click();
  await page.getByRole("option", { name: "Money", exact: true }).click();
  await expect(experiments.getByLabel("Unit or amount meaning", { exact: true })).toHaveValue("");
  await expect(experiments.getByLabel("What the value covers", { exact: true })).toHaveValue("");
  await expect(experiments.getByLabel("What the comparison covers(optional)", { exact: true })).toHaveValue("");
  await experiments.getByLabel("Unit or amount meaning", { exact: true }).fill("net contribution");
  await experiments.getByLabel("Recorded currency", { exact: true }).fill("KWD");
  await experiments.getByLabel("Recorded value(optional)", { exact: true }).fill("-1.234");
  await experiments.getByLabel("What the value covers", { exact: true }).fill("One synthetic job after variable costs; excludes overhead");
  await experiments.getByRole("button", { name: "Save", exact: true }).click();
  await expect(savedNotice).toBeVisible();
  await expect(savedNotice).toHaveCount(0, { timeout: 10_000 });
  await expect(experiments).toContainText("1.234");
  await expect(experiments).toContainText("KWD");
  await expect(experiments).toContainText("Comparison value: Unknown");
  await expect(experiments).toContainText("Changed definition");
  await expectNoHorizontalScroll(page);
  await expectAccessible(page, "Reported contribution measurement");
  await experiments.screenshot({ path: testInfo.outputPath("contribution-measurement.png") });
  const moneyReport = (await rows("experiments")).find(row => row.orgId === org._id)!;
  expect((moneyReport.analyses as { measurement?: unknown }[]).at(-1)?.measurement).toMatchObject({ type: "monetary", value: -1234, comparisonValue: null, currency: "KWD" });
  await page.getByRole("tab", { name: "Research", exact: true }).click();
  await page.getByText("Who to reach and how", { exact: true }).click();
  const detailedTests = page.getByRole("region", { name: "Experiments", exact: true });
  await expect(detailedTests).toContainText("1.234");
  await expect(detailedTests).toContainText("KWD");
  await expect(detailedTests).toContainText("Changed definition");
  await planViews.getByRole("tab", { name: "Next steps", exact: true }).click();
  await primaryLearning.getByRole("button", { name: "Discuss next step", exact: true }).click();
  const message = page.getByRole("textbox", { name: "Message Climb AI", exact: true });
  await expect(message).toHaveValue(/Read its original test and latest report/);
  await expect(message).toHaveValue(new RegExp(fixture.focusedMove.title));
  await message.fill("Review this saved result with me before choosing what to do next.");
  await expect(message).toHaveValue("Review this saved result with me before choosing what to do next.");
  expect(await snapshot()).toEqual(before);
});
