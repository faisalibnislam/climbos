import { expect, test } from "@playwright/test";
import { expectAccessible, expectNoHorizontalScroll, openDemo } from "./helpers";
import { localDemoFixtures } from "./local-demo-fixtures";
import { focusedPlanFixture } from "../tests/fixtures/focusedPlan";

const envFile = process.env.CLIMBOS_DESIGN_E2E_ENV_FILE;
const { rows, append } = localDemoFixtures(envFile);
const copyRow = (row: Record<string, unknown>) => Object.fromEntries(Object.entries(row).filter(([key]) => key !== "_id" && key !== "_creationTime"));

test("focused plan exposes all three options and selecting bold grants no action authority @mobile", async ({ page, baseURL }, testInfo) => {
  test.skip(!envFile, "Requires explicitly configured isolated loopback fixtures");
  test.setTimeout(150_000);
  expect(baseURL).toBe("http://127.0.0.1:3420");
  const demoSlug = await openDemo(page);
  const original = (await rows("organizations")).find(row => row.slug === demoSlug);
  if (!original || original.kind !== "demo") throw new Error("Isolated demo required");
  const member = (await rows("memberships")).find(row => row.orgId === original._id);
  const business = (await rows("businesses")).find(row => row.orgId === original._id);
  const goal = (await rows("goals")).find(row => row.orgId === original._id && row.status === "active");
  const plan = (await rows("strategies")).find(row => row.orgId === original._id);
  if (!member || !business || !goal || !plan) throw new Error("Demo records required");
  const slug = `focused-options-${testInfo.project.name}-${Date.now()}`;
  await append("organizations", [{ ...copyRow(original), slug, name: "Synthetic strategy options" }]);
  const org = (await rows("organizations")).find(row => row.slug === slug)!;
  await append("memberships", [{ ...copyRow(member), orgId: org._id }]);
  await append("businesses", [{ ...copyRow(business), orgId: org._id }]);
  const savedBusiness = (await rows("businesses")).find(row => row.orgId === org._id)!;
  await append("goals", [{ ...copyRow(goal), orgId: org._id }]);
  const savedGoal = (await rows("goals")).find(row => row.orgId === org._id)!;
  const fixture = focusedPlanFixture();
  await append("strategies", [{ ...copyRow(plan), orgId: org._id, businessId: savedBusiness._id, goalId: savedGoal._id, runId: undefined, approvalId: undefined, summary: fixture.summary, expert: { ...(plan.expert as Record<string, unknown>), focusedMove: fixture.focusedMove, strategicDirection: fixture.strategicDirection, strategyExploration: fixture.strategyExploration, preparedWork: fixture.preparedWork, timing: fixture.timing, phases: fixture.phases, weekOneChecklist: fixture.weekOneChecklist, plays: [] } }]);
  const snapshot = async () => Promise.all(["artifacts", "approvals", "actionReceipts", "workflowRuns"].map(async table => (await rows(table)).filter(row => row.orgId === org._id)));
  const before = await snapshot();
  await page.goto(`/app/${slug}/plan`);
  await expect(page.getByRole("tab", { name: "Next steps", exact: true })).toHaveAttribute("aria-selected", "true");
  await page.getByRole("tab", { name: "Strategy options", exact: true }).click();
  const section = page.getByRole("region", { name: "Grounded, adjacent and bold strategy options" });
  for (const mode of ["grounded", "adjacent", "bold"] as const) await expect(section.getByRole("heading", { name: fixture.strategyExploration[mode].title })).toBeVisible();
  await expect(section).toContainText("not an execution ranking");
  await expect(section).toContainText("it does not start work");
  const bold = section.locator("article").filter({ has: page.getByRole("heading", { name: fixture.strategyExploration.bold.title }) });
  await bold.getByText("Explore the idea and its test", { exact: true }).click();
  await expect(bold).toContainText("No matching precedent used");
  await expect(bold).toContainText("Continue if:");
  await expect(bold).toContainText("Change if:");
  await expect(bold).toContainText("Stop if:");
  await bold.getByRole("combobox", { name: "Your decision", exact: true }).click();
  await page.getByRole("option", { name: "Select this option", exact: true }).click();
  await bold.getByRole("button", { name: "Save feedback", exact: true }).click();
  await expect(bold).toContainText("Last owner record: selected; test not started");
  expect((await rows("strategyExplorationFeedback")).filter(row => row.orgId === org._id)).toMatchObject([{ mode: "bold", decision: "selected", testState: "not_started" }]);
  const learning = page.locator("details").filter({ has: page.locator("summary", { hasText: "What new plans learn from your feedback" }) });
  await learning.locator("summary").click();
  await expect(learning).toContainText("1 included");
  await expect(learning).toContainText("Included for the next plan");
  await learning.getByRole("button", { name: "Stop using", exact: true }).click();
  await expect(learning).toContainText("0 included");
  await expect(learning).toContainText("Retired");
  await learning.getByRole("button", { name: "Use again", exact: true }).click();
  await expect(learning).toContainText("1 included");
  await bold.getByRole("combobox", { name: "Your decision", exact: true }).click();
  await page.getByRole("option", { name: "Reject this option", exact: true }).click();
  await bold.getByRole("button", { name: "Save feedback", exact: true }).click();
  await expect(learning).toContainText("Replaced by a newer report");
  await expect(learning).toContainText("1 included");
  await expect(learning.getByRole("button", { name: "Stop using", exact: true })).toHaveCount(1);
  await expectNoHorizontalScroll(page);
  await expectAccessible(page, "Focused strategy options");
  await bold.screenshot({ path: testInfo.outputPath("bold-option.png") });
  expect(await snapshot()).toEqual(before);
});
