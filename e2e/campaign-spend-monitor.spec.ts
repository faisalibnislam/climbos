import { expect, test } from "@playwright/test";
import { expectAccessible, expectNoHorizontalScroll, openDemo } from "./helpers";
import { localDemoFixtures } from "./local-demo-fixtures";

const envFile = process.env.CLIMBOS_DESIGN_E2E_ENV_FILE;
const { rows, append } = localDemoFixtures(envFile);
const copyRow = ({ _id: _i, _creationTime: _c, ...data }: Record<string, unknown>) => data;

test("requires reviewed spend-monitor approval and preserves demo isolation @mobile", async ({ page, baseURL }, testInfo) => {
  test.skip(!envFile, "Requires isolated loopback fixtures");
  test.setTimeout(120_000);
  page.setDefaultTimeout(15_000);
  expect(baseURL).toBe("http://127.0.0.1:3420");
  const demoSlug = await openDemo(page);
  const original = (await rows("organizations")).find(r => r.slug === demoSlug);
  if (!original || original.kind !== "demo") throw new Error("Demo workspace required");
  const member = (await rows("memberships")).find(r => r.orgId === original._id);
  const policy = (await rows("autonomyPolicies")).find(r => r.orgId === original._id && r.active);
  if (!member || !policy) throw new Error("Demo owner and policy required");
  const slug = `ad-monitor-${testInfo.project.name}-${Date.now()}`;
  await append("organizations", [{ ...copyRow(original), slug, name: "Spend monitor fixture", currency: "USD" }]);
  const org = (await rows("organizations")).find(r => r.slug === slug)!;
  await append("memberships", [{ ...copyRow(member), orgId: org._id }]);
  await append("autonomyPolicies", [{ ...copyRow(policy), orgId: org._id, currency: "USD", mode: "review", allowAdPauseRules: true, approvalTtlHours: 72 }]);
  const now = Date.now();
  await append("connections", [{ orgId: org._id, provider: "google_ads", status: "connected", externalAccountId: "1234567890", scopes: [], isFixture: true, createdBy: member.userId, createdAt: now, updatedAt: now }]);
  const connection = (await rows("connections")).find(r => r.orgId === org._id)!;
  const startDate = new Date(now - 6 * 86_400_000).toISOString().slice(0, 10);
  const endDate = new Date(now + 2 * 86_400_000).toISOString().slice(0, 10);
  await append("campaigns", [{ orgId: org._id, name: "Monitor approval fixture", channel: "google_search_ad", status: "active", dailyBudgetMinor: 1000, budgetEnvelopeMinor: 9000, budgetUnitVersion: "currency-minor-v1", currency: "USD", startDate, endDate, stopRules: ["Review reported spend"], connectionId: connection._id, externalId: "42", createdAt: now, updatedAt: now }]);
  const errors: string[] = [];
  page.on("pageerror", e => errors.push(e.message));
  await page.goto(`/app/${slug}/content?tab=ads`);
  await page.getByRole("tab", { name: "Ads", exact: true }).click();
  const monitor = page.getByRole("region", { name: "Campaign spend monitor" });
  await expect(monitor.getByText("Spend-limit pause · Off", { exact: true })).toBeVisible();
  const approvals = async () => (await rows("approvals")).filter(r => r.orgId === org._id && r.subjectType === "campaign_monitor");
  expect(await approvals()).toHaveLength(0);
  await monitor.getByRole("button", { name: "Review spend monitor" }).click();
  const dialog = page.getByRole("alertdialog");
  await expect(dialog.getByText(/Account 1234567890 · Campaign 42/)).toBeVisible();
  await expect(dialog.getByText(/Authorize one pause attempt at \$90.00/)).toBeVisible();
  await expect(dialog.getByText(/Approval lasts 72 hours/)).toBeVisible();
  await dialog.evaluate(async element => { await Promise.all(element.getAnimations({ subtree: true }).map(animation => animation.finished)); });
  await expectAccessible(page, "spend monitor approval");
  await expectNoHorizontalScroll(page);
  await page.screenshot({ path: testInfo.outputPath("spend-monitor-approval.png"), fullPage: true });
  await dialog.getByRole("button", { name: "Cancel", exact: true }).click();
  expect(await approvals()).toHaveLength(0);
  await monitor.getByRole("button", { name: "Review spend monitor" }).click();
  await dialog.getByRole("button", { name: "Approve spend monitor", exact: true }).click();
  await expect(monitor.getByText(/Demo monitor only/)).toBeVisible();
  const approved = await approvals();
  expect(approved).toHaveLength(1);
  expect(approved[0]).toMatchObject({ status: "approved", decidedBy: member.userId, actionKind: "pause_at_reported_total", scope: { externalAccountId: "1234567890", externalCampaignId: "42", totalSpendLimitMinor: 9000, currency: "USD" } });
  expect((await rows("actionReceipts")).filter(r => r.orgId === org._id)).toHaveLength(0);
  await monitor.getByRole("button", { name: "Stop monitoring" }).click();
  await expect(monitor.getByText("Spend-limit pause · Off", { exact: true })).toBeVisible();
  expect((await approvals())[0].status).toBe("invalidated");
  expect((await rows("campaigns")).find(r => r.orgId === org._id)?.status).toBe("active");
  await expectAccessible(page, "spend monitor stopped");
  expect(errors).toEqual([]);
});
